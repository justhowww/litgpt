def test_fim_baseline_bytes_use_the_exact_missing_interval(tmp_path):
    path = tmp_path / "stream.h264"
    path.write_bytes(b"outer-prefixABCDEFGHIJ-outer-suffix")
    sample = ReconstructionSample(
        h264_path=path,
        target_start=12,
        target_end=22,
        target_nal_index=3,
        frame_index=0,
        prompt_ids=torch.tensor([SPAN_BOS_ID]),
        prompt_region_ids=torch.tensor([REGION_BRIDGE]),
        prompt_offset_ids=torch.tensor([3]),
        target_length=4,
        task="fim",
        replacement_start=3,
        replacement_end=7,
    )

    assert (
        _ground_truth_replacement(path.read_bytes(), sample) == b"DEFG"
    )  # Ground-truth baseline restores exactly the held-out gap.
    assert (
        _deterministic_random_bytes(sample, 4)
        == _deterministic_random_bytes(sample, 4)
    )  # Random baseline is reproducible across checkpoint evaluations.
    assert (
        len(_deterministic_random_bytes(sample, 4)) == 4
    )  # Random baseline preserves the oracle missing-span length.


def test_parse_ppm_and_identical_image_metrics():
    ppm = b"P6\n2 1\n255\n" + bytes([0, 10, 20, 30, 40, 50])

    image = parse_ppm(ppm)

    assert image.shape == (1, 2, 3)  # PPM dimensions become HWC RGB.
    assert math.isinf(image_psnr(image, image))  # Identical frames have infinite PSNR.
    assert abs(image_ssim(image, image) - 1.0) < 1e-6  # Identical frames have perfect SSIM.


def test_error_exploding_rejects_nonzero_ffmpeg_exit(monkeypatch):
    ppm = b"P6\n1 1\n255\n" + bytes([0, 10, 20])
    commands = []

    def fake_run(command, **kwargs):
        commands.append(command)
        return SimpleNamespace(returncode=1, stdout=ppm)

    monkeypatch.setattr("litgpt.eval.byte_reconstruction.subprocess.run", fake_run)

    normal_image, normal_status = decode_frame(b"stream", 0, "ffmpeg", 5)
    strict_image, strict_status = decode_frame(
        b"stream", 0, "ffmpeg", 5, error_exploding=True
    )

    assert normal_image is not None  # Normal mode accepts a frame produced with decoder warnings.
    assert normal_status == "decoded"  # Normal mode reports the available frame as decoded.
    assert strict_image is None  # Error-exploding mode rejects output from a failed FFmpeg process.
    assert strict_status == "decoder_error"  # The strict failure remains distinguishable in probe metrics.
    assert "-err_detect" not in commands[0]  # Normal decoding leaves FFmpeg concealment behavior unchanged.
    assert commands[1][commands[1].index("-err_detect") + 1] == "explode"  # Strict mode requests error explosion.


def test_strict_syntax_disables_concealment_and_checks_multiple_error_classes(monkeypatch):
    commands = []

    def fake_run(command, **kwargs):
        commands.append(command)
        return SimpleNamespace(returncode=1, stdout=b"")

    monkeypatch.setattr("litgpt.eval.byte_reconstruction.subprocess.run", fake_run)

    image, status = decode_frame(
        b"stream", 0, "ffmpeg", 5, strict_syntax=True
    )

    assert image is None  # Strict MRT decoding does not accept a failed decoder output.
    assert status == "decoder_error"  # Syntax rejection is distinct from a missing frame.
    assert commands[0][commands[0].index("-ec") + 1] == "0"  # Concealment is disabled.
    assert (
        commands[0][commands[0].index("-err_detect") + 1]
        == "explode+bitstream+buffer+compliant"
    )  # Multiple syntax/error classes are fatal.


def test_reconstruction_probe_defaults_to_strict_concealment_free_decoding(
    tmp_path, monkeypatch
):
    path = tmp_path / "stream.h264"
    path.write_bytes(b"stream")
    sample = ReconstructionSample(
        h264_path=path,
        target_start=0,
        target_end=6,
        target_nal_index=0,
        frame_index=0,
        prompt_ids=torch.tensor([SPAN_BOS_ID]),
        prompt_region_ids=torch.tensor([REGION_BRIDGE]),
        prompt_offset_ids=torch.tensor([0]),
        target_length=1,
    )
    strict_flags = []

    def fake_decode(*args, strict_syntax=False, **kwargs):
        strict_flags.append(strict_syntax)
        return torch.zeros((1, 1, 3)), "decoded"

    monkeypatch.setattr("litgpt.byte.reconstruction.decode_frame", fake_decode)
    monkeypatch.setattr(
        "litgpt.byte.reconstruction.generate_target_slice",
        lambda *args, **kwargs: SimpleNamespace(data=b"x", stopped=False),
    )

    metrics = run_reconstruction_probe(
        torch.nn.Identity(),
        [sample],
        ReconstructionEvalConfig(),
        torch.device("cpu"),
    )

    assert strict_flags == [
        True,
        True,
    ]  # Reference and generated streams both disable concealment.
    assert (
        metrics["reconstruction/decode_rate"] == 1.0
    )  # Top-level decode rate is the strict result.
    assert (
        metrics["reconstruction/model_learned/strict/decode_rate"] == 1.0
    )  # The strict series is retained explicitly for TensorBoard inspection.


def test_reconstruction_metrics_are_namespaced_by_task():
    metrics = {
        "reconstruction/decode_rate": 1.0,
        "reconstruction/psnr_mean_valid": 37.0,
    }

    namespaced = _namespace_reconstruction_metrics(metrics, "fim")

    assert (
        namespaced["reconstruction/fim/decode_rate"] == 1.0
    )  # FIM decode rate cannot overwrite the AR probe at the same step.
    assert (
        namespaced["reconstruction/fim/psnr_mean_valid"] == 37.0
    )  # FIM visual quality retains its own TensorBoard series.
