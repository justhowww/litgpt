"""Incremental, forkable CAVLC macroblock automaton for constrained decoding.

The parser in ``h264_syntax.py`` reads whole syntax elements per call and cannot
be paused between bits, so it can only answer "is this byte legal?" by re-parsing
the whole NAL per candidate -- O(256 x NAL) per generated byte. This module is the
steppable equivalent: a state machine over RBSP *bits* that consumes one bit at a
time (``consume_bit``), can be cheaply cloned to explore alternatives, and reaches
``COMPLETE_MB``/``DONE`` structurally (no RBSP-length dependence). From it we
compile a 256-byte legal-continuation mask without replaying the NAL prefix.

Scope: Constrained Baseline, CAVLC, P/I slices (the corpus we generate). It decodes
the *entire* MB (mb_skip_run -> mb_type -> prediction -> cbp -> mb_qp_delta ->
residual) because reaching residual with correct nC/cbp context requires consuming
every prior field. Fields whose legal set is bounded (mb_type, sub_mb_type, ref_idx,
intra_chroma_pred_mode, cbp, and 8-bit mb_qp_delta) are pruned while decoding.
Motion-vector differences accept every successfully decoded se(v); their derived
level-dependent range is outside this slice-data automaton.
I_PCM is handled as raw bytes. B-slices / non-CAVLC are out of scope.

Stdlib-only (imports only ``h264_cavlc_tables``) so tests load it by path.

Mirrors, bit-for-bit: ``_residual_block`` / ``_parse_residual`` / ``_parse_macroblock``
/ ``_parse_inter_pred`` / ``_NNZ`` in ``h264_syntax.py``.
"""

