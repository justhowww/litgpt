#!/usr/bin/env python3
"""Byte-exact AR replay on the exact training windows (overfit check O0).

Rebuilds every training GOP window from ``train_split.json`` exactly as the
training loader does (``ByteStreamWindowDataset.ar_item``), then for each window:

* teacher-forced: one full forward; top-1 accuracy over every label (bytes + EOS)
  and whether the final EOS is the argmax;
* free run: prompt = BOS + the window's first frame (its parameter sets and IDR),
  greedy, unmasked, until EOS or ``len(target) + slack`` bytes. Success means the
  generated bytes followed by EOS equal the GT remainder followed by EOS.

For a failure, the first wrong byte is attributed to the GT syntax element(s)
that own it. Only plain byte transformers (``byte_patch_size == 1``) are
supported: this is the simplest-setup probe, not a MEGABYTE evaluation.

Output: OUT/summary.json and OUT/windows.jsonl.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

import torch

_ROOT = Path(__file__).resolve().parents[4]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from litgpt.byte import h264_syntax as HS  # noqa: E402
from litgpt.byte.data import (  # noqa: E402
    BYTE_VOCAB_SIZE,
    IGNORE_INDEX,
    SEQ_EOS_ID,
    ByteStreamWindowDataset,
    load_manifest_rows,
    load_nal_index,
)
from scripts.byte.eval.helpers.checkpoint_eval_helpers import (  # noqa: E402
    jsonable,
    load_model,
)

_INDEX_CHARS = str.maketrans("", "", "0123456789[]")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("run_dir", type=Path, help="Run directory with train_split.json")
    parser.add_argument("--checkpoint", default="final", help="final or step-XXXXXXXX")
    parser.add_argument("--split", choices=("train", "val"), default="train")
    parser.add_argument("--nal-index-path", type=Path, required=True)
    parser.add_argument("--window-min-frames", type=int, default=2)
    parser.add_argument("--max-windows", type=int, default=0, help="0 = all")
    parser.add_argument(
        "--slack-bytes",
        type=int,
        default=256,
        help="Free-run budget beyond the GT remainder before declaring an overrun.",
    )
    parser.add_argument("--out-dir", type=Path, default=None)
    parser.add_argument("--device", default="cuda")
    return parser.parse_args()


def build_dataset(split: dict[str, Any], args: argparse.Namespace) -> ByteStreamWindowDataset:
    if int(split["byte_patch_size"]) != 1:
        raise ValueError("eval_overfit_ar.py supports only byte_patch_size == 1")
    rows = load_manifest_rows(
        Path(split["manifest"]), max_rows=split.get("max_manifest_rows") or None
    )
    nal_index = load_nal_index(args.nal_index_path, Path(split["manifest"]), rows)
    return ByteStreamWindowDataset(
        rows,
        max_seq_length=int(split["raw_byte_budget"]),
        min_frames=args.window_min_frames,
        p_fim=0.0,
        use_eos=bool(split["use_eos"]),
        window_unit=split["window_unit"],
        nal_index=nal_index,
        seed=int(split["seed"]),
    )


def select_windows(
    dataset: ByteStreamWindowDataset, split: dict[str, Any], which: str
) -> list[int]:
    train_windows = {
        (str(Path(w["h264_path"])), int(w["start_nal"]), int(w["end_nal"]))
        for w in split["windows"]
    }
    train_videos = {str(Path(v)) for v in split["videos"]}
    indices = []
    for index, sample in enumerate(dataset.samples):
        key = (str(sample.h264_path), int(sample.start_nal), int(sample.end_nal))
        if which == "train" and key in train_windows:
            indices.append(index)
        elif which == "val" and str(sample.h264_path) not in train_videos:
            indices.append(index)
    if which == "train" and len(indices) != len(train_windows):
        raise RuntimeError(
            f"rebuilt {len(indices)} of {len(train_windows)} recorded training windows; "
            "check manifest, NAL index, and --window-min-frames"
        )
    return indices


def first_divergence_syntax(window: bytes, offset: int) -> tuple[str, str | None]:
    try:
        spans = HS.parse_stream(window, parse_slice_data=True).all_spans()
    except Exception:
        return "parser unavailable", None
    owners = [s for s in spans if s.byte_start <= offset < s.byte_end]
    names = ", ".join(dict.fromkeys(s.name.translate(_INDEX_CHARS) for s in owners))
    categories = ", ".join(sorted({s.category.value for s in owners})) or None
    return names or "unattributed", categories


@torch.inference_mode()
def evaluate_window(
    model: torch.nn.Module,
    dataset: ByteStreamWindowDataset,
    index: int,
    device: torch.device,
    slack_bytes: int,
) -> dict[str, Any]:
    sample = dataset.samples[index]
    item = dataset.ar_item(index)
    input_ids = item["input_ids"].to(device)
    labels = item["labels"].to(device)
    region_ids = item["region_ids"].to(device)
    offset_ids = item["offset_ids"].to(device)
    window = bytes(t for t in labels.tolist() if 0 <= t < BYTE_VOCAB_SIZE)

    with torch.autocast(device_type=device.type, dtype=torch.bfloat16, enabled=device.type == "cuda"):
        logits = model(
            input_ids.unsqueeze(0),
            region_ids=region_ids.unsqueeze(0),
            offset_ids=offset_ids.unsqueeze(0),
        )[0]
    supervised = labels != IGNORE_INDEX
    predicted = logits.argmax(dim=-1)
    tf_correct = int((predicted[supervised] == labels[supervised]).sum())
    tf_total = int(supervised.sum())
    eos_label = labels[-1].item() == SEQ_EOS_ID
    tf_eos_correct = bool(eos_label and predicted[-1].item() == SEQ_EOS_ID)

    # Prompt = BOS + bytes through the end of the window's first frame. Label k is
    # window byte k, and input position k + 1 holds that byte.
    frames = dataset._frame_bounds(sample, sample.h264_path.read_bytes())
    if len(frames) < 2:
        raise RuntimeError(f"window {index} has fewer than two frames")
    prompt_bytes = frames[0][1]
    prompt_len = prompt_bytes + 1
    target = labels[prompt_bytes:].tolist()  # remaining bytes (+ EOS)
    max_new = len(target) + slack_bytes

    raw = model
    raw.set_kv_cache(
        batch_size=1,
        max_seq_length=raw.max_seq_length,
        device=device,
        dtype=torch.bfloat16 if device.type == "cuda" else next(raw.parameters()).dtype,
    )
    generated: list[int] = []
    stop_reason = "budget"
    try:
        with torch.autocast(device_type=device.type, dtype=torch.bfloat16, enabled=device.type == "cuda"):
            step_logits = raw(
                input_ids[:prompt_len].unsqueeze(0),
                input_pos=torch.arange(prompt_len, device=device),
                input_pos_maxp1=prompt_len,
                region_ids=region_ids[:prompt_len].unsqueeze(0),
                offset_ids=offset_ids[:prompt_len].unsqueeze(0),
            )[0, -1]
            budget = min(max_new, raw.max_seq_length - prompt_len)
            for step in range(budget):
                # Greedy over the inference action set: 256 bytes plus EOS.
                token = int(step_logits[:BYTE_VOCAB_SIZE].argmax())
                if step_logits[SEQ_EOS_ID] > step_logits[token]:
                    token = SEQ_EOS_ID
                generated.append(token)
                if token == SEQ_EOS_ID:
                    stop_reason = "eos"
                    break
                position = prompt_len + step
                aux = min(position, input_ids.numel() - 1)
                step_logits = raw(
                    torch.tensor([[token]], device=device),
                    input_pos=torch.tensor([position], device=device),
                    input_pos_maxp1=position + 1,
                    region_ids=region_ids[aux : aux + 1].unsqueeze(0),
                    offset_ids=offset_ids[aux : aux + 1].unsqueeze(0),
                )[0, -1]
    finally:
        raw.clear_kv_cache()

    common = 0
    for want, got in zip(target, generated):
        if want != got:
            break
        common += 1
    exact = generated == target
    row: dict[str, Any] = {
        "dataset_index": index,
        "h264_path": str(sample.h264_path),
        "start_nal": int(sample.start_nal),
        "end_nal": int(sample.end_nal),
        "window_bytes": len(window),
        "frames": len(frames),
        "prompt_bytes": prompt_bytes,
        "target_tokens": len(target),
        "generated_tokens": len(generated),
        "stop_reason": stop_reason,
        "tf_byte_acc": tf_correct / max(tf_total, 1),
        "tf_wrong_tokens": tf_total - tf_correct,
        "tf_eos_correct": tf_eos_correct,
        "byte_exact": exact,
        "common_prefix_tokens": common,
        "common_prefix_fraction": common / max(len(target), 1),
        "first_divergence_kind": None,
        "first_divergence_window_offset": None,
        "first_divergence_syntax": None,
        "first_divergence_category": None,
    }
    if not exact:
        if common == len(generated):
            kind = "budget"
        elif generated[common] == SEQ_EOS_ID:
            kind = "early_eos"
        elif target[common] == SEQ_EOS_ID:
            kind = "missed_eos"
        else:
            kind = "wrong_byte"
        row["first_divergence_kind"] = kind
        offset = prompt_bytes + common
        row["first_divergence_window_offset"] = offset
        if offset < len(window):
            syntax, category = first_divergence_syntax(window, offset)
            row["first_divergence_syntax"] = syntax
            row["first_divergence_category"] = category
    return row


def summarize(rows: list[dict[str, Any]]) -> dict[str, Any]:
    n = len(rows)

    def mean(key: str) -> float | None:
        return sum(float(r[key]) for r in rows) / n if n else None

    tf_wrong = sum(int(r["tf_wrong_tokens"]) for r in rows)
    tf_total = sum(int(r["target_tokens"]) for r in rows)
    return {
        "windows": n,
        "byte_exact_count": sum(bool(r["byte_exact"]) for r in rows),
        "byte_exact_rate": mean("byte_exact"),
        "tf_byte_acc_mean": mean("tf_byte_acc"),
        "tf_windows_perfect": sum(int(r["tf_wrong_tokens"]) == 0 for r in rows),
        "tf_wrong_tokens_total": tf_wrong,
        "tf_eos_correct_rate": mean("tf_eos_correct"),
        "common_prefix_fraction_mean": mean("common_prefix_fraction"),
        "free_run_tokens_total": tf_total,
        "stop_reason_hist": dict(Counter(r["stop_reason"] for r in rows).most_common()),
        "first_divergence_kind_hist": dict(
            Counter(r["first_divergence_kind"] for r in rows if r["first_divergence_kind"]).most_common()
        ),
        "first_divergence_syntax_hist": dict(
            Counter(r["first_divergence_syntax"] for r in rows if r["first_divergence_syntax"]).most_common()
        ),
    }


def main() -> None:
    args = parse_args()
    split = json.loads((args.run_dir / "train_split.json").read_text(encoding="utf-8"))
    out_dir = args.out_dir or args.run_dir / "eval_overfit_ar" / args.checkpoint / args.split
    out_dir.mkdir(parents=True, exist_ok=False)
    device = torch.device(args.device)

    dataset = build_dataset(split, args)
    indices = select_windows(dataset, split, args.split)
    if args.max_windows:
        indices = indices[: args.max_windows]
    print(f"[overfit-ar] split={args.split} windows={len(indices)}", flush=True)

    model = load_model(args.run_dir / args.checkpoint, device)
    if int(model.config.byte_patch_size) != 1:
        raise ValueError("checkpoint is not a plain byte transformer (byte_patch_size != 1)")

    rows = []
    with (out_dir / "windows.jsonl").open("w", encoding="utf-8") as handle:
        for count, index in enumerate(indices, 1):
            row = evaluate_window(model, dataset, index, device, args.slack_bytes)
            rows.append(row)
            handle.write(json.dumps(jsonable(row)) + "\n")
            handle.flush()
            print(
                f"[overfit-ar] {count}/{len(indices)} exact={row['byte_exact']} "
                f"tf_acc={row['tf_byte_acc']:.4f} prefix={row['common_prefix_fraction']:.3f} "
                f"div={row['first_divergence_kind']}:{row['first_divergence_syntax']}",
                flush=True,
            )
    summary = summarize(rows)
    (out_dir / "summary.json").write_text(json.dumps(jsonable(summary), indent=2) + "\n", encoding="utf-8")
    print(json.dumps(jsonable(summary), indent=2), flush=True)


if __name__ == "__main__":
    main()
