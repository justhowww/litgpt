@dataclass(frozen=True)
class WindowFimSample:
    sample_index: int
    h264_path: Path
    start_nal: int
    end_nal: int
    frame_lo: int
    frame_hi: int
    split: int
    gap: int
    prompt_ids: Tensor
    prompt_region_ids: Tensor
    prompt_offset_ids: Tensor
    teacher_input_ids: Tensor
    teacher_region_ids: Tensor
    teacher_offset_ids: Tensor
    teacher_labels: Tensor
    target_bytes: bytes
    window_bytes: bytes
    hole_id: int | None = None
    corruption_frame_type: str | None = None

    @property
    def target_length(self) -> int:
        return len(self.target_bytes)

    @property
    def bytes_before_hole(self) -> bytes:
        return self.window_bytes[: self.split]

    @property
    def bytes_after_hole(self) -> bytes:
        return self.window_bytes[self.split + self.gap : self.frame_hi]

    @property
    def gt_truncated_stream(self) -> bytes:
        return self.window_bytes[: self.frame_hi]

    @property
    def corrupted_stream(self) -> bytes:
        """The decoder input with the sampled FIM span physically removed."""
        return self.bytes_before_hole + self.bytes_after_hole

    @property
    def corrupted_full_stream(self) -> bytes:
        """The full sampled window with the FIM span physically removed."""
        return (
            self.window_bytes[: self.split] + self.window_bytes[self.split + self.gap :]
        )

    def repaired_stream(self, generated: bytes) -> bytes:
        return (
            self.window_bytes[: self.split]
            + generated
            + self.window_bytes[self.split + self.gap : self.frame_hi]
        )

    def repaired_full_stream(self, generated: bytes) -> bytes:
        """The full sampled window with ``generated`` inserted into the hole."""
        return (
            self.window_bytes[: self.split]
            + generated
            + self.window_bytes[self.split + self.gap :]
        )


