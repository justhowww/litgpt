def _load_train_split(path: Path) -> tuple[set[tuple[str, int, int]], set[str]]:
    split = json.loads(path.read_text(encoding="utf-8"))
    windows = {
        (str(Path(w["h264_path"])), int(w["start_nal"]), int(w["end_nal"]))
        for w in split.get("windows", [])
    }
    videos = {str(Path(v)) for v in split.get("videos", [])}
    return windows, videos


def _split_indices(
    dataset: ByteStreamWindowDataset, args: argparse.Namespace
) -> list[int]:
    all_indices = list(range(len(dataset)))
    if args.eval_split == "all":
        return all_indices
    if args.split_by_video:
        videos = sorted({str(s.h264_path) for s in dataset.samples})
        generator = torch.Generator().manual_seed(args.seed)
        perm = torch.randperm(len(videos), generator=generator).tolist()
        n_val = max(1, int(len(videos) * args.val_fraction))
        val_videos = {videos[i] for i in perm[:n_val]}
        if args.eval_split == "val":
            return [
                i
                for i, s in enumerate(dataset.samples)
                if str(s.h264_path) in val_videos
            ]
        return [
            i
            for i, s in enumerate(dataset.samples)
            if str(s.h264_path) not in val_videos
        ]

    val_size = max(1, int(len(dataset) * args.val_fraction))
    train_size = len(dataset) - val_size
    if train_size <= 0:
        raise RuntimeError("Need at least two usable windows for train/val split")
    generator = torch.Generator().manual_seed(args.seed)
    perm = torch.randperm(len(dataset), generator=generator).tolist()
    return perm[train_size:] if args.eval_split == "val" else perm[:train_size]


def build_eval_samples(args: argparse.Namespace) -> list[WindowFimSample]:
    rows = load_manifest_rows(
        args.manifest, max_rows=args.max_manifest_rows or None, report_progress=True,
    )
    index_path = args.nal_index_path or default_nal_index_path(args.manifest)
    nal_index = (
        load_nal_index(index_path, args.manifest, rows)
        if index_path.is_file()
        else None
    )
    if args.nal_index_path is not None and nal_index is None:
        raise FileNotFoundError(f"NAL index does not exist: {index_path}")

    dataset = ByteStreamWindowDataset(
        rows,
        max_seq_length=args.max_window_bytes,
        min_frames=args.window_min_frames,
        p_fim=1.0,
        fim_format=args.fim_format,
        use_eos=args.use_eos,
        fim_min_gap=args.fim_min_gap,
        fim_max_gap=args.fim_max_gap,
        frame_guard_bytes=args.slice_header_guard_bytes,
        resample_fim=False,
        nal_index=nal_index,
        seed=args.seed,
    )

    if args.train_split_file is not None:
        train_windows, train_videos = _load_train_split(args.train_split_file)
        if train_windows:
            indices = [
                i
                for i, s in enumerate(dataset.samples)
                if (str(s.h264_path), int(s.start_nal), int(s.end_nal)) in train_windows
            ]
            split_desc = (
                f"{len(indices)} exact train windows from {args.train_split_file}"
            )
        else:
            indices = [
                i
                for i, s in enumerate(dataset.samples)
                if str(s.h264_path) in train_videos
            ]
            split_desc = f"{len(indices)} train videos from {args.train_split_file}"
        if not indices:
            raise RuntimeError(
                "No dataset windows matched -- check manifest/max rows against train_split.json"
            )
        print(f"train-split filter: {split_desc}", flush=True)
    else:
        indices = _split_indices(dataset, args)
        print(
            f"split filter: eval_split={args.eval_split} selected {len(indices)}/{len(dataset)} windows",
            flush=True,
        )

    selected: list[WindowFimSample] = []
    for idx in indices:
        item = dataset[idx]
        if item["sample_meta"].get("task") != "fim":
            continue
        labels: Tensor = item["labels"]
        supervised = labels != IGNORE_INDEX
        if not bool(supervised.any()):
            continue
        target_ids = labels[supervised].tolist()
        if args.use_eos:
            if not target_ids or target_ids[-1] != SEQ_EOS_ID:
                continue
            target_ids = target_ids[:-1]
        if not target_ids or any(t < 0 or t >= BYTE_VOCAB_SIZE for t in target_ids):
            continue

        first_supervised = int(supervised.nonzero()[0])
        prompt_end = first_supervised + 1
        meta = item["sample_meta"]
        window_bytes = bytes(dataset.ar_item(idx)["labels"].tolist())
        selected.append(
            WindowFimSample(
                sample_index=idx,
                h264_path=Path(meta["h264_path"]),
                start_nal=int(meta["start_nal"]),
                end_nal=int(meta["end_nal"]),
                frame_lo=int(meta["frame_lo"]),
                frame_hi=int(meta["frame_hi"]),
                split=int(meta["fim_split"]),
                gap=int(meta["fim_gap"]),
                prompt_ids=item["input_ids"][:prompt_end].clone(),
                prompt_region_ids=item["region_ids"][:prompt_end].clone(),
                prompt_offset_ids=item["offset_ids"][:prompt_end].clone(),
                teacher_input_ids=item["input_ids"].clone(),
                teacher_region_ids=item["region_ids"].clone(),
                teacher_offset_ids=item["offset_ids"].clone(),
                teacher_labels=item["labels"].clone(),
                target_bytes=bytes(target_ids),
                window_bytes=window_bytes,
            )
        )
        if len(selected) >= args.num_clips:
            break

    if not selected:
        raise RuntimeError(
            "No FIM samples selected. Lower gap/guard constraints or check that window-FIM is reachable."
        )
    print(f"Selected {len(selected)} FIM AVC-LM samples", flush=True)
    return selected


def _sample_token(logits: Tensor, temperature: float, top_k: int, top_p: float) -> int:
    if temperature <= 0 and top_k <= 0 and top_p >= 1.0:
        return int(logits.argmax(dim=-1))
    logits = logits.float()
    if temperature > 0:
        logits = logits / temperature
    if top_k > 0:
        k = min(top_k, logits.numel())
        kth = torch.topk(logits, k).values[-1]
        logits = torch.where(
            logits < kth, torch.full_like(logits, float("-inf")), logits
        )
    if 0 < top_p < 1.0:
        sorted_logits, sorted_idx = torch.sort(logits, descending=True)
        probs = F.softmax(sorted_logits, dim=-1)
        cumulative = probs.cumsum(dim=-1)
        remove_sorted = cumulative > top_p
        remove_sorted[0] = False
        remove = torch.zeros_like(remove_sorted).scatter(0, sorted_idx, remove_sorted)
        logits = torch.where(remove, torch.full_like(logits, float("-inf")), logits)
    probs = F.softmax(logits, dim=-1)
    return int(torch.multinomial(probs, num_samples=1))


@torch.inference_mode()
def generate_span(
    model: nn.Module,
    sample: WindowFimSample,
    device: torch.device,
    *,
    stop_mode: str,
    temperature: float,
    top_k: int,
    top_p: float,
    max_gen_multiple: float,
    max_gen_extra: int,
    mask_illegal_bytes: bool,
    slice_max_mbs: int,
) -> GenerationResult | None:
    raw = _unwrap_model(model)
    raw.eval()
    prompt = sample.prompt_ids.to(device).unsqueeze(0)
    region_ids = sample.prompt_region_ids.to(device).unsqueeze(0)
    offset_ids = sample.prompt_offset_ids.to(device).unsqueeze(0)
    prompt_len = prompt.size(1)
    if prompt_len >= raw.max_seq_length:
        return None
    if stop_mode == "oracle_len":
        max_new = sample.target_length
    elif stop_mode == "learned_eos":
        max_new = min(
            max(
                sample.target_length + max_gen_extra,
                int(sample.target_length * max_gen_multiple),
            ),
            raw.max_seq_length - prompt_len + 1,
        )
    else:
        raise ValueError(f"unknown stop_mode: {stop_mode}")
    if max_new <= 0:
        return None

    mask_state: HM.MaskState | None = None
    if mask_illegal_bytes:
        # Seed from the ORIGINAL stream order.  The PSM prompt contains markers and
        # places the orphan before generation, so advancing over prompt_ids would
        # describe the wrong H.264 parser state.
        mask_state = HM.MaskState(slice_max_mbs=slice_max_mbs, fail_closed=True)
        for byte in sample.bytes_before_hole:
            HM.advance(mask_state, byte)
        mask_state.generation_started = True

    cache_dtype = (
        torch.bfloat16 if device.type == "cuda" else next(raw.parameters()).dtype
    )
    raw.set_kv_cache(
        batch_size=1,
        max_seq_length=raw.max_seq_length,
        device=device,
        dtype=cache_dtype,
    )
    generated: list[int] = []
    eos_stopped = False
    stop_reason = "budget"
    mask_argmax_rejected = 0
    mask_eos_checks = 0
    mask_eos_blocked = 0
    mask_probability_mass_sum = 0.0
    mask_probability_mass_count = 0
    first_mask_intervention: dict[str, Any] | None = None
    try:
        with torch.autocast(
            device_type=device.type,
            dtype=torch.bfloat16,
            enabled=device.type == "cuda",
        ):
            logits = raw(
                prompt,
                input_pos=torch.arange(prompt_len, device=device, dtype=torch.long),
                input_pos_maxp1=prompt_len,
                region_ids=region_ids,
                offset_ids=offset_ids,
            )
        for generated_idx in range(max_new):
            next_logits = logits[0, -1]
            byte_logits = next_logits[:BYTE_VOCAB_SIZE].clone()
            if mask_state is not None:
                allowed = HM.get_valid_byte_mask(mask_state)
                if not any(allowed):
                    stop_reason = "mask_boxed_in"
                    break
                raw_byte_argmax = int(next_logits[:BYTE_VOCAB_SIZE].argmax(dim=-1))
                if not allowed[raw_byte_argmax]:
                    mask_argmax_rejected += 1
                    if first_mask_intervention is None:
                        auto = mask_state.automaton
                        first_mask_intervention = {
                            "generated_byte": generated_idx,
                            "nal_index": mask_state.nal_index,
                            "model_argmax": raw_byte_argmax,
                            "stage": (
                                "nal_header"
                                if mask_state.expect_nal_header
                                else getattr(auto, "stage", "unknown")
                            ),
                            "syntax": (
                                "nal_header"
                                if mask_state.expect_nal_header
                                else getattr(auto, "ae_tag", "unknown")
                            ),
                        }
                allowed_tensor = torch.tensor(
                    allowed, dtype=torch.bool, device=byte_logits.device
                )
                log_total = torch.logsumexp(
                    next_logits[:BYTE_VOCAB_SIZE].float(), dim=0
                )
                log_allowed = torch.logsumexp(
                    next_logits[:BYTE_VOCAB_SIZE][allowed_tensor].float(), dim=0
                )
                mask_probability_mass_sum += float(
                    torch.exp(log_allowed - log_total).item()
                )
                mask_probability_mass_count += 1
                byte_logits[~allowed_tensor] = float("-inf")

            if stop_mode == "learned_eos":
                eos_allowed = mask_state is None
                if mask_state is not None:
                    # For greedy decoding, avoid the suffix probe unless EOS can
                    # actually beat the best legal byte. Sampling must know the full
                    # support, so it always performs the check.
                    sampling = not (temperature <= 0 and top_k <= 0 and top_p >= 1.0)
                    best_byte = byte_logits.max()
                    eos_competitive = bool(
                        sampling
                        or not torch.isfinite(best_byte)
                        or next_logits[SEQ_EOS_ID] >= best_byte
                    )
                    if eos_competitive:
                        mask_eos_checks += 1
                        eos_allowed = HM.can_append_bytes(
                            mask_state, sample.bytes_after_hole, require_complete=True,
                        )
                        if not eos_allowed:
                            mask_eos_blocked += 1
                eos_logit = next_logits[SEQ_EOS_ID : SEQ_EOS_ID + 1].clone()
                if not eos_allowed:
                    eos_logit.fill_(float("-inf"))
                allowed_logits = torch.cat((byte_logits, eos_logit))
                if not torch.isfinite(allowed_logits).any():
                    stop_reason = "mask_boxed_in"
                    break
                token = _sample_token(allowed_logits, temperature, top_k, top_p)
                token = SEQ_EOS_ID if token == BYTE_VOCAB_SIZE else token
                if token == SEQ_EOS_ID:
                    eos_stopped = True
                    stop_reason = "eos"
                    break
            else:
                if not torch.isfinite(byte_logits).any():
                    stop_reason = "mask_boxed_in"
                    break
                token = _sample_token(byte_logits, temperature, top_k, top_p)

            if token < 0 or token >= BYTE_VOCAB_SIZE:
                stop_reason = f"invalid_token_{token}"
                break
            generated.append(token)
            if mask_state is not None:
                HM.advance(mask_state, token)
            if generated_idx == max_new - 1:
                stop_reason = "oracle_len" if stop_mode == "oracle_len" else "budget"
                break

            position = prompt_len + generated_idx
            with torch.autocast(
                device_type=device.type,
                dtype=torch.bfloat16,
                enabled=device.type == "cuda",
            ):
                logits = raw(
                    torch.tensor([[token]], device=device, dtype=torch.long),
                    input_pos=torch.tensor([position], device=device, dtype=torch.long),
                    input_pos_maxp1=position + 1,
                    region_ids=torch.tensor(
                        [[REGION_BRIDGE]], device=device, dtype=torch.long
                    ),
                    offset_ids=torch.tensor(
                        [[generated_idx + 1]], device=device, dtype=torch.long
                    ),
                )
    finally:
        raw.clear_kv_cache()
    return GenerationResult(
        bytes(generated),
        eos_stopped,
        stop_reason,
        len(generated),
        mask_calls=mask_state.mask_calls if mask_state is not None else 0,
        mask_strict_calls=mask_state.strict_mask_calls if mask_state is not None else 0,
        mask_permissive_calls=(
            mask_state.permissive_mask_calls if mask_state is not None else 0
        ),
        mask_argmax_rejected=mask_argmax_rejected,
        mask_eos_checks=mask_eos_checks,
        mask_eos_blocked=mask_eos_blocked,
        mask_failure_reason=(
            mask_state.failure_reason if mask_state is not None else None
        ),
        mask_probability_mass_sum=mask_probability_mass_sum,
        mask_probability_mass_count=mask_probability_mass_count,
        first_mask_intervention=first_mask_intervention,
    )


@torch.inference_mode()
def teacher_forced_span_metrics(
    model: nn.Module, sample: WindowFimSample, device: torch.device,
) -> dict[str, Any] | None:
    """Teacher-forced accuracy on the exact same FIM target span used for generation."""
    raw = _unwrap_model(model)
    raw.eval()
    if sample.teacher_input_ids.numel() > raw.max_seq_length:
        return None
    idx = sample.teacher_input_ids.to(device).unsqueeze(0)
    labels = sample.teacher_labels.to(device).unsqueeze(0)
    region_ids = sample.teacher_region_ids.to(device).unsqueeze(0)
    offset_ids = sample.teacher_offset_ids.to(device).unsqueeze(0)
    with torch.autocast(
        device_type=device.type, dtype=torch.bfloat16, enabled=device.type == "cuda",
    ):
        logits = raw(idx, region_ids=region_ids, offset_ids=offset_ids)
    supervised = labels != IGNORE_INDEX
    supervised_labels = labels[supervised]
    if supervised_labels.numel() == 0:
        return None
    pred = logits.argmax(dim=-1)[supervised]
    byte_mask = supervised_labels < BYTE_VOCAB_SIZE
    eos_mask = supervised_labels == SEQ_EOS_ID
    byte_total = int(byte_mask.sum())
    eos_total = int(eos_mask.sum())
    byte_correct = (
        int((pred[byte_mask] == supervised_labels[byte_mask]).sum())
        if byte_total
        else 0
    )
    eos_correct = int((pred[eos_mask] == SEQ_EOS_ID).sum()) if eos_total else 0
    loss = F.cross_entropy(
        logits.view(-1, logits.size(-1)), labels.view(-1), ignore_index=IGNORE_INDEX,
    )
    element_correct: dict[str, list[int]] = {}
    element_legal: dict[str, list[int]] = {}
    element_illegal_different: dict[str, list[int]] = {}
    if byte_total == sample.target_length:
        try:
            spans = HS.parse_stream(
                sample.gt_truncated_stream, parse_slice_data=True
            ).all_spans()
            gt_list = list(sample.target_bytes)
            pred_list = [int(x) for x in pred[byte_mask].detach().cpu().tolist()]
            (
                element_correct,
                element_legal,
                element_illegal_different,
            ) = AR._value_legal_hits(
                spans,
                sample.split,
                sample.split + sample.target_length,
                gt_list,
                pred_list,
            )
        except Exception:
            # The strict decoder/parser diagnostics below remain authoritative. A
            # failed optional TF attribution must not discard the sample.
            pass
    return {
        "tf_ce_nats": float(loss),
        "tf_target_tokens": int(supervised_labels.numel()),
        "tf_byte_total": byte_total,
        "tf_byte_correct": byte_correct,
        "tf_byte_acc": byte_correct / max(byte_total, 1),
        "tf_eos_total": eos_total,
        "tf_eos_correct": eos_correct,
        "tf_eos_acc": eos_correct / max(eos_total, 1) if eos_total else None,
        "element_correct_counts": element_correct,
        "syntax_legal_counts": element_legal,
        "syntax_illegal_when_different_counts": element_illegal_different,
    }


_INDEX_RE = re.compile(r"\[\d+\]")


def repaired_stream_diagnostics(
    stream: bytes, generated_start: int, generated_length: int
) -> dict[str, Any]:
    """Locate the first syntax failure and count generated bytes before it.

    A generated span is not required to match GT. It survives until the repaired
    stream's own parser state first becomes inconsistent. If failure is discovered
    in the fixed suffix, all generated bytes were consumed, but decode success can
    still be false because the generated state did not reconnect to that suffix.
    """
    try:
        parsed = HS.parse_stream(stream, parse_slice_data=True)
    except Exception as exc:  # defensive: parser diagnostics should not kill eval
        return {
            "parse_ok": False,
            "parse_error": type(exc).__name__,
            "nals": 0,
            "completed_bytes": 0,
            "desync_region": "unknown",
            "desync_category": "unknown",
            "desync_reason": type(exc).__name__,
            "first_desync": generated_start,
        }
    statuses = [getattr(n.status, "name", str(n.status)) for n in parsed.nals]
    bad = next((n for n in parsed.nals if n.status != HS.ParseStatus.OK), None)
    first_desync: int | None = None
    region = "none"
    category = "none"
    reason = "none"
    failure_context = None
    if bad is not None:
        first_desync = (
            bad.desync_byte if bad.desync_byte is not None else bad.nal.payload_end
        )
        reason = bad.reason_kind or getattr(bad.status, "name", str(bad.status))
        failure_context = bad.failure_context
        if bad.failure_element:
            region = _INDEX_RE.sub("", bad.failure_element)
        selected_span = bad.spans[-1] if bad.spans else None
        if bad.desync_bit is not None and bad.spans:
            prior = [s for s in bad.spans if s.bit_start <= bad.desync_bit]
            if prior:
                selected_span = prior[-1]
        if region == "none" and selected_span is not None:
            region = _INDEX_RE.sub("", selected_span.name)
        if isinstance(failure_context, dict) and failure_context.get("category"):
            category = str(failure_context["category"])
        elif selected_span is not None:
            category = selected_span.category.value

    if first_desync is None:
        completed = generated_length
    else:
        completed = max(
            0, min(generated_length, int(first_desync) - int(generated_start))
        )
    return {
        "parse_ok": bad is None,
        "parse_status_hist": {s: statuses.count(s) for s in sorted(set(statuses))},
        "nals": len(parsed.nals),
        "completed_bytes": completed,
        "desync_region": region,
        "desync_category": category,
        "desync_reason": reason,
        "first_desync": first_desync,
        "failure_context": failure_context,
    }


def save_fim_videos(
    viz: dict[int, dict[str, Any]],
    frame_dir: Path,
    checkpoint_name: str,
    stop_mode: str,
    args: argparse.Namespace,
) -> None:
    if not viz:
        return
    print(
        f"Saving {len(viz)} FIM GT-versus-repaired videos for "
        f"{checkpoint_name}/{stop_mode}",
        flush=True,
    )
    for sample_id, item in viz.items():
        out_path = frame_dir / f"sample_{sample_id:04d}_{stop_mode}.mp4"
        saved = save_comparison_video(
            reference_frames=item["gt_frames"],
            result_frames=item["model_frames"],
            out_path=out_path,
            ffmpeg_binary=args.ffmpeg_binary,
            fps=args.viz_fps,
            timeout_sec=args.timeout_sec,
            columns=("GT video", "repaired video"),
            border_changes_at=item["target_frame"],
            thumbnail_frame=item["target_frame"],
            metadata={
                "checkpoint": checkpoint_name,
                "sample_id": sample_id,
                "stop_mode": stop_mode,
                "target_frame": item["target_frame"],
                "strict_valid": item["strict_valid"],
                "h264_path": item["h264_path"],
            },
        )
        if not saved:
            print(f"  FIM video failed for sample {sample_id}", flush=True)


def write_jsonl(
    path: Path, rows: Iterable[dict[str, Any]], *, append: bool = True
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = "a" if append else "w"
    with path.open(mode, encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(jsonable(row), sort_keys=True) + "\n")


def summarize(
    details: list[dict[str, Any]],
    *,
    skipped_prompt_or_budget: int = 0,
    skipped_gt_decode_short: int = 0,
    mask_enabled: bool = False,
    decode_enabled: bool = True,
) -> dict[str, Any]:
    """Aggregate FIM with the same meanings and names as AR continuation."""
    completed_bytes = [int(r["completed_bytes"]) for r in details]
    target_bytes = [int(r["target_bytes"]) for r in details]
    completed_frames = [int(r.get("completed_frames", 0)) for r in details]
    desync_regions = Counter(r.get("desync_region") or "none" for r in details)
    desync_categories = Counter(r.get("desync_category") or "none" for r in details)
    desync_reasons = Counter(r.get("desync_reason") or "none" for r in details)
    stop_reasons = Counter(r.get("stop_reason") or "none" for r in details)
    strict_statuses = Counter(
        r.get("strict_decode_status") or "not_run" for r in details
    )
    mask_failure_reasons = Counter(
        r["mask_failure_reason"] for r in details if r.get("mask_failure_reason")
    )
    first_interventions = Counter(
        r["first_mask_intervention"].get("syntax") or "unknown"
        for r in details
        if r.get("first_mask_intervention")
    )

    elem_correct: dict[str, list[int]] = {}
    elem_legal: dict[str, list[int]] = {}
    elem_illegal_different: dict[str, list[int]] = {}
    for row in details:
        AR._merge_counts(elem_correct, row.get("element_correct_counts", {}))
        AR._merge_counts(elem_legal, row.get("syntax_legal_counts", {}))
        AR._merge_counts(
            elem_illegal_different, row.get("syntax_illegal_when_different_counts", {}),
        )

    probability_count = sum(
        int(r.get("mask_probability_mass_count", 0)) for r in details
    )
    probability_sum = sum(
        float(r.get("mask_probability_mass_sum", 0.0)) for r in details
    )
    mask_calls = sum(int(r.get("mask_calls", 0)) for r in details)
    strict_calls = sum(int(r.get("mask_strict_calls", 0)) for r in details)
    rejected = sum(int(r.get("mask_argmax_rejected", 0)) for r in details)
    decode_seconds = [
        float(r["strict_decode_seconds"])
        for r in details
        if r.get("strict_decode_seconds") is not None
    ]
    timeout_partial = Counter(
        int(r.get("timeout_complete_frames", 0))
        for r in details
        if r.get("strict_decode_status") == "timeout"
    )
    psnr = [
        float(r["cont_psnr_mean"])
        for r in details
        if r.get("cont_psnr_mean") is not None
    ]
    ssim = [
        float(r["cont_ssim_mean"])
        for r in details
        if r.get("cont_ssim_mean") is not None
    ]
    tf_rows = [r for r in details if r.get("tf_byte_acc") is not None]
    real_app = [
        r["real_appearance_features"]
        for r in details
        if r.get("real_appearance_features")
    ]
    gen_app = [
        r["gen_appearance_features"]
        for r in details
        if r.get("gen_appearance_features")
    ]
    real_mot = [
        r["real_motion_features"] for r in details if r.get("real_motion_features")
    ]
    gen_mot = [
        r["gen_motion_features"] for r in details if r.get("gen_motion_features")
    ]
    n = len(details)

    out: dict[str, Any] = {
        "num_clips": n,
        "num_skipped_prompt_or_budget": skipped_prompt_or_budget,
        "num_skipped_gt_decode_short": skipped_gt_decode_short,
        "success_rate": (
            AR.mean([1.0 if r.get("strict_valid") else 0.0 for r in details])
            if decode_enabled
            else None
        ),
        "completed_frames_mean": AR.mean([float(x) for x in completed_frames]),
        "completed_frames_total": sum(completed_frames),
        "completed_bytes_mean": AR.mean([float(x) for x in completed_bytes]),
        "completed_bytes_median": (
            float(sorted(completed_bytes)[len(completed_bytes) // 2])
            if completed_bytes
            else None
        ),
        "completed_bytes_max": (
            float(max(completed_bytes)) if completed_bytes else None
        ),
        "completed_bytes_total": sum(completed_bytes),
        "target_frames": 1,
        "target_frames_total": n,
        "target_bytes_mean": AR.mean([float(x) for x in target_bytes]),
        "target_bytes_median": (
            float(sorted(target_bytes)[len(target_bytes) // 2])
            if target_bytes
            else None
        ),
        "target_bytes_max": float(max(target_bytes)) if target_bytes else None,
        "target_bytes_total": sum(target_bytes),
        "desync_region_top": (
            desync_regions.most_common(1)[0][0] if desync_regions else None
        ),
        "desync_region_hist": dict(desync_regions.most_common()),
        "desync_category_hist": dict(desync_categories.most_common()),
        "desync_reason_hist": dict(desync_reasons.most_common()),
        "generation_stop_reason_hist": dict(stop_reasons.most_common()),
        "strict_decode_status_hist": dict(strict_statuses.most_common()),
        "strict_decode_timeout_count": strict_statuses.get("timeout", 0),
        "strict_decode_seconds_mean": AR.mean(decode_seconds),
        "strict_decode_seconds_max": max(decode_seconds) if decode_seconds else None,
        "timeout_complete_frames_hist": dict(timeout_partial),
        "cont_psnr_mean": AR.mean(psnr),
        "cont_ssim_mean": AR.mean(ssim),
        "eos_stop_rate": AR.mean(
            [1.0 if r.get("eos_stopped") else 0.0 for r in details]
        ),
        "tf_byte_acc_mean": AR.mean([float(r["tf_byte_acc"]) for r in tf_rows]),
        "tf_ce_nats_mean": AR.mean([float(r["tf_ce_nats"]) for r in tf_rows]),
        "tf_eos_acc_mean": AR.mean(
            [float(r["tf_eos_acc"]) for r in tf_rows if r.get("tf_eos_acc") is not None]
        ),
        "element_correct": {
            e: {"acc": h / t, "n": t}
            for e, (h, t) in sorted(elem_correct.items())
            if t >= 16
        },
        "syntax_legal_by_element": {
            e: {"legal_rate": h / t, "count": t}
            for e, (h, t) in sorted(elem_legal.items())
            if t >= 16
        },
        "syntax_illegal_when_different_by_element": {
            e: {"illegal_rate": h / t, "illegal_count": h, "different_count": t,}
            for e, (h, t) in sorted(elem_illegal_different.items())
            if t > 0
        },
        "mask_failure_reason_hist": (
            dict(mask_failure_reasons.most_common()) if mask_enabled else None
        ),
        "mask_calls_total": mask_calls if mask_enabled else None,
        "mask_strict_calls_total": strict_calls if mask_enabled else None,
        "mask_permissive_calls_total": (
            sum(int(r.get("mask_permissive_calls", 0)) for r in details)
            if mask_enabled
            else None
        ),
        "mask_strict_call_rate": (
            strict_calls / mask_calls if mask_enabled and mask_calls else None
        ),
        "mask_argmax_rejected_total": rejected if mask_enabled else None,
        "mask_decisions_measured_total": probability_count if mask_enabled else None,
        "mask_argmax_rejection_rate": (
            rejected / probability_count if mask_enabled and probability_count else None
        ),
        "mask_allowed_probability_mass_mean": (
            probability_sum / probability_count
            if mask_enabled and probability_count
            else None
        ),
        "mask_first_intervention_syntax_hist": (
            dict(first_interventions.most_common()) if mask_enabled else None
        ),
        "mask_eos_checks_total": (
            sum(int(r.get("mask_eos_checks", 0)) for r in details)
            if mask_enabled
            else None
        ),
        "mask_eos_blocked_total": (
            sum(int(r.get("mask_eos_blocked", 0)) for r in details)
            if mask_enabled
            else None
        ),
    }
    out.update(AR.distribution_metrics(real_app, gen_app, real_mot, gen_mot))
    return out


def main() -> None:
    args = parse_args()
    HM.configure_debug(args.mask_debug)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    device = torch.device(
        args.device if args.device == "cpu" or torch.cuda.is_available() else "cpu"
    )
    samples = build_eval_samples(args)
    (args.out_dir / "config.json").write_text(
        json.dumps(jsonable(vars(args)), indent=2) + "\n", encoding="utf-8"
    )
    sample_manifest = [
        {
            "sample_id": i,
            "dataset_index": s.sample_index,
            "h264_path": str(s.h264_path),
            "start_nal": s.start_nal,
            "end_nal": s.end_nal,
            "frame_lo": s.frame_lo,
            "frame_hi": s.frame_hi,
            "split": s.split,
            "gap": s.gap,
            "target_length": s.target_length,
        }
        for i, s in enumerate(samples)
    ]
    (args.out_dir / "samples.json").write_text(
        json.dumps(jsonable(sample_manifest), indent=2) + "\n", encoding="utf-8"
    )

    metrics_path = args.out_dir / "metrics.jsonl"
    details_path = args.out_dir / "sample_details.jsonl"
    summaries: list[dict[str, Any]] = []

    for checkpoint_dir in args.checkpoint_dirs:
        model = load_model(checkpoint_dir, device)
        ckpt_name = checkpoint_dir.name
        stream_dir = args.out_dir / "streams" / ckpt_name
        if args.save_streams:
            stream_dir.mkdir(parents=True, exist_ok=True)
        print(f"[{ckpt_name}] teacher-forced and GT decode setup", flush=True)
        tf_cache = [
            teacher_forced_span_metrics(model, sample, device) for sample in samples
        ]
        gt_cache: list[tuple[list[Tensor], str, dict[str, Any]]] = []
        for sample in samples:
            if args.decode:
                gt_cache.append(
                    AR.decode_h264(
                        sample.gt_truncated_stream, args, strict=True, max_frames=None,
                    )
                )
            else:
                gt_cache.append(([], "not_run", {}))
        for stop_mode in args.stop_modes:
            print(f"[{ckpt_name}] FIM AVC-LM stop_mode={stop_mode}", flush=True)
            rows: list[dict[str, Any]] = []
            viz: dict[int, dict[str, Any]] = {}
            skipped_prompt_or_budget = 0
            skipped_gt_decode_short = 0
            for sample_id, sample in enumerate(samples):
                tf_metrics = tf_cache[sample_id]
                gt_frames, gt_status, gt_decode = gt_cache[sample_id]
                if args.decode and (gt_status != "decoded" or not gt_frames):
                    skipped_gt_decode_short += 1
                    rows.append(
                        {
                            "checkpoint": ckpt_name,
                            "stop_mode": stop_mode,
                            "sample_id": sample_id,
                            "dataset_index": sample.sample_index,
                            "error": "gt_decode_short",
                            "gt_strict_decode_status": gt_status,
                            "gt_ffmpeg_decode": gt_decode,
                        }
                    )
                    continue
                result = generate_span(
                    model,
                    sample,
                    device,
                    stop_mode=stop_mode,
                    temperature=args.temperature,
                    top_k=args.top_k,
                    top_p=args.top_p,
                    max_gen_multiple=args.max_gen_multiple,
                    max_gen_extra=args.max_gen_extra,
                    mask_illegal_bytes=args.mask_illegal_bytes,
                    slice_max_mbs=args.slice_max_mbs,
                )
                if result is None:
                    skipped_prompt_or_budget += 1
                    row = {
                        "checkpoint": ckpt_name,
                        "stop_mode": stop_mode,
                        "sample_id": sample_id,
                        "dataset_index": sample.sample_index,
                        "error": "prompt_or_budget_too_long",
                    }
                    rows.append(row)
                    continue

                model_stream = sample.repaired_stream(result.data)
                gt_stream = sample.gt_truncated_stream
                gt_parse = repaired_stream_diagnostics(
                    gt_stream, sample.split, sample.target_length
                )
                model_parse = repaired_stream_diagnostics(
                    model_stream, sample.split, len(result.data)
                )
                row = {
                    "checkpoint": ckpt_name,
                    "stop_mode": stop_mode,
                    "sample_id": sample_id,
                    "dataset_index": sample.sample_index,
                    "h264_path": str(sample.h264_path),
                    "start_nal": sample.start_nal,
                    "end_nal": sample.end_nal,
                    "frame_lo": sample.frame_lo,
                    "frame_hi": sample.frame_hi,
                    "split": sample.split,
                    "gap": sample.gap,
                    "target_length": sample.target_length,
                    "generated_length": len(result.data),
                    "target_bytes": sample.target_length,
                    "completed_bytes": model_parse["completed_bytes"],
                    "completed_frames": 0,
                    "target_frames": 1,
                    "eos_stopped": result.eos_stopped,
                    "stop_reason": result.stop_reason,
                    "mask_enabled": args.mask_illegal_bytes,
                    "mask_calls": result.mask_calls,
                    "mask_strict_calls": result.mask_strict_calls,
                    "mask_permissive_calls": result.mask_permissive_calls,
                    "mask_argmax_rejected": result.mask_argmax_rejected,
                    "mask_eos_checks": result.mask_eos_checks,
                    "mask_eos_blocked": result.mask_eos_blocked,
                    "mask_failure_reason": result.mask_failure_reason,
                    "mask_probability_mass_sum": result.mask_probability_mass_sum,
                    "mask_probability_mass_count": result.mask_probability_mass_count,
                    "first_mask_intervention": result.first_mask_intervention,
                    "gt_parse_ok": gt_parse.get("parse_ok", False),
                    "model_parse_ok": model_parse.get("parse_ok", False),
                    "desync_region": model_parse["desync_region"],
                    "desync_category": model_parse["desync_category"],
                    "desync_reason": model_parse["desync_reason"],
                    "first_desync": model_parse["first_desync"],
                    "gt_parse": gt_parse,
                    "model_parse": model_parse,
                }
                if tf_metrics is not None:
                    row.update(tf_metrics)
                if args.save_streams:
                    stem = f"sample_{sample_id:04d}_{stop_mode}"
                    gt_path = stream_dir / f"{stem}_gt.h264"
                    model_path = stream_dir / f"{stem}_model.h264"
                    missing_path = stream_dir / f"{stem}_missing_gt.bin"
                    gen_path = stream_dir / f"{stem}_missing_model.bin"
                    gt_path.write_bytes(gt_stream)
                    model_path.write_bytes(model_stream)
                    missing_path.write_bytes(sample.target_bytes)
                    gen_path.write_bytes(result.data)
                    row.update(
                        {
                            "gt_stream_path": str(gt_path),
                            "model_stream_path": str(model_path),
                            "gt_missing_path": str(missing_path),
                            "model_missing_path": str(gen_path),
                        }
                    )
                if args.decode:
                    model_frames, model_status, model_decode = AR.decode_h264(
                        model_stream, args, strict=True, max_frames=None
                    )
                    prefix_frames = max(0, len(gt_frames) - 1)
                    produced = max(0, min(1, len(model_frames) - prefix_frames))
                    strict_valid = model_status == "decoded" and produced >= 1
                    row.update(
                        {
                            "prefix_frames": prefix_frames,
                            "completed_frames": produced,
                            "strict_valid": strict_valid,
                            "strict_decode_status": model_status,
                            "strict_decode_seconds": model_decode.get(
                                "elapsed_seconds"
                            ),
                            "timeout_complete_frames": model_decode.get(
                                "complete_frames_before_exit", 0
                            ),
                            "ffmpeg_decode": model_decode,
                        }
                    )
                    target_index = len(gt_frames) - 1
                    row["real_appearance_features"] = AR.appearance_features(
                        gt_frames[target_index]
                    )
                    if target_index > 0:
                        row["real_motion_features"] = AR.motion_features(
                            gt_frames[target_index], gt_frames[target_index - 1]
                        )
                    if (
                        target_index < len(model_frames)
                        and model_frames[target_index].shape
                        == gt_frames[target_index].shape
                    ):
                        p = AR.image_psnr(
                            gt_frames[target_index], model_frames[target_index]
                        )
                        row["cont_psnr_mean"] = (
                            AR.PSNR_PERFECT_CAP if p == float("inf") else p
                        )
                        row["cont_ssim_mean"] = AR.image_ssim(
                            gt_frames[target_index], model_frames[target_index]
                        )
                        row["gen_appearance_features"] = AR.appearance_features(
                            model_frames[target_index]
                        )
                        if target_index > 0:
                            row["gen_motion_features"] = AR.motion_features(
                                model_frames[target_index],
                                model_frames[target_index - 1],
                            )
                    if sample_id < args.num_visualizations:
                        comparison_path = (
                            args.out_dir
                            / "frames"
                            / ckpt_name
                            / f"sample_{sample_id:04d}_{stop_mode}.mp4"
                        )
                        viz[sample_id] = {
                            "gt_frames": [frame.cpu() for frame in gt_frames],
                            "model_frames": [frame.cpu() for frame in model_frames],
                            "target_frame": prefix_frames,
                            "strict_valid": strict_valid,
                            "h264_path": str(sample.h264_path),
                        }
                        row["comparison_video_path"] = str(comparison_path)
                else:
                    row.update(
                        {"strict_valid": None, "strict_decode_status": "not_run",}
                    )
                rows.append(row)
            if args.decode:
                save_fim_videos(
                    viz,
                    args.out_dir / "frames" / ckpt_name,
                    ckpt_name,
                    stop_mode,
                    args,
                )
            write_jsonl(details_path, rows)
            valid_rows = [r for r in rows if "error" not in r]
            summary = {
                "checkpoint": ckpt_name,
                "checkpoint_dir": str(checkpoint_dir),
                "mode": "fim_avclm",
                "stop_mode": stop_mode,
                **summarize(
                    valid_rows,
                    skipped_prompt_or_budget=skipped_prompt_or_budget,
                    skipped_gt_decode_short=skipped_gt_decode_short,
                    mask_enabled=args.mask_illegal_bytes,
                    decode_enabled=args.decode,
                ),
            }
            write_jsonl(metrics_path, [summary])
            summaries.append(summary)
            print(
                f"[{ckpt_name}/{stop_mode}] success={summary.get('success_rate')!s} "
                f"frames={summary.get('completed_frames_total', 0)}/"
                f"{summary.get('target_frames_total', 0)} "
                f"bytes={summary.get('completed_bytes_total', 0)}/"
                f"{summary.get('target_bytes_total', 0)} "
                f"desync_top={summary.get('desync_region_top')}",
                flush=True,
            )

    if summaries:
        fieldnames = sorted({k for row in summaries for k in row.keys()})
        with (args.out_dir / "summary.csv").open(
            "w", newline="", encoding="utf-8"
        ) as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            for row in summaries:
                writer.writerow(jsonable(row))


if __name__ == "__main__":
    main()
