"""AVC-LM window-FIM span reconstruction evaluation.

This is the Phase-2 FIM-side probe for the AVC-LM per-macroblock-slice corpus.
It evaluates the exact window-FIM training format:

    context, FIM_BEGIN, prefix, FIM_HOLE, orphan, FIM_END -> missing span [, EOS]

The deployable stopping modes are learned EOS and parser reconnection. Parser
reconnection stops as soon as the generated middle can be followed by the fixed
suffix and leave a complete H.264 parse. The optional oracle-length mode is kept
only as a debug diagnostic; it is not a valid repair-time stopping rule.

The headline ``success_rate`` requires both correct autonomous termination and a
successful strict FFmpeg decode. Generated bytes do not have to equal the removed
GT bytes or have the same length; they only have to form a self-consistent H.264
continuation that reconnects to the fixed suffix and produces the target frame.

This is deliberately not the BSCV artifact-repair benchmark. On this corpus the
hole can span many tiny per-MB NALs, so the result should be read as "can the
AVC-LM FIM objective reconstruct held-out spans under its own data layout?", not
as a one-slice-per-frame corruption-recovery product metric.

``--hole-placement corrupt_gen_frame`` supplies the deployment-oriented AVC-LM
variant: choose a complete frame access unit, remove an exact whole-byte span at
a fixed relative position, and compare the repaired target frame with FFmpeg's
default-concealment baseline. It intentionally stays byte-aligned because the
model's repair target is a sequence of complete bytes.

Usage:
    python scripts/byte/eval/eval_fim_avclm.py MANIFEST \
        --nal-index-path DATA/nal_index.sqlite \
        --checkpoint-dirs RUN/step-XXXX [...] \
        --train-split-file RUN/train_split.json \
        --out-dir RUN/eval_fim/train/step-XXXX
"""

