@dataclass(frozen=True)
class WindowFimSample:
    sample_index: int
    h264_path: Path
    start_nal: int
    end_nal: int
    frame_lo: int
    frame_hi: int
    split: int
    gap: int
    prompt_ids: Tensor
    prompt_region_ids: Tensor
    prompt_offset_ids: Tensor
    teacher_input_ids: Tensor
    teacher_region_ids: Tensor
    teacher_offset_ids: Tensor
    teacher_labels: Tensor
    target_bytes: bytes
    window_bytes: bytes

    @property
    def target_length(self) -> int:
        return len(self.target_bytes)

    @property
    def bytes_before_hole(self) -> bytes:
        return self.window_bytes[: self.split]

    @property
    def bytes_after_hole(self) -> bytes:
        return self.window_bytes[self.split + self.gap : self.frame_hi]

    @property
    def gt_truncated_stream(self) -> bytes:
        return self.window_bytes[: self.frame_hi]

    def repaired_stream(self, generated: bytes) -> bytes:
        return (
            self.window_bytes[: self.split]
            + generated
            + self.window_bytes[self.split + self.gap : self.frame_hi]
        )


@dataclass(frozen=True)
class GenerationResult:
    data: bytes
    eos_stopped: bool
    stop_reason: str
    steps: int
    mask_calls: int = 0
    mask_strict_calls: int = 0
    mask_permissive_calls: int = 0
    mask_argmax_rejected: int = 0
    mask_eos_checks: int = 0
    mask_eos_blocked: int = 0
    mask_failure_reason: str | None = None
    mask_probability_mass_sum: float = 0.0
    mask_probability_mass_count: int = 0
    first_mask_intervention: dict[str, Any] | None = None


