def _requested_corruption_lengths(args: argparse.Namespace) -> list[int]:
    """Return the ordered corrupt_gen_frame deletion schedule."""

    scheduled = getattr(args, "corr_len_bytes_list", None)
    if scheduled is not None:
        return [int(length) for length in scheduled]
    scalar = getattr(args, "corr_len_bytes", None)
    return [int(scalar)] if scalar is not None else []


def _load_train_split(
    path: Path,
) -> tuple[
    set[tuple[str, int, int]],
    set[str],
    dict[tuple[str, int, int], list[dict[str, Any]]],
]:
    split = json.loads(path.read_text(encoding="utf-8"))
    windows = {
        (str(Path(w["h264_path"])), int(w["start_nal"]), int(w["end_nal"]))
        for w in split.get("windows", [])
    }
    videos = {str(Path(v)) for v in split.get("videos", [])}
    fixed_holes: dict[tuple[str, int, int], list[dict[str, Any]]] = {}
    for h in split.get("fixed_fim_holes", []):
        key = (
            str(Path(h["h264_path"])),
            int(h["start_nal"]),
            int(h["end_nal"]),
        )
        fixed_holes.setdefault(key, []).append(h)
    for holes in fixed_holes.values():
        holes.sort(key=lambda h: int(h.get("hole_id", 0)))
    return windows, videos, fixed_holes


def _resolve_fim_loss_scope(args: argparse.Namespace) -> str:
    """Resolve the training loss layout before constructing evaluation samples."""
    requested = args.fim_loss_scope
    if requested != "auto":
        return str(requested)
    if args.train_split_file is not None:
        split = json.loads(args.train_split_file.read_text(encoding="utf-8"))
        recorded = split.get("fim_loss_scope")
        if recorded in FIM_LOSS_SCOPES:
            print(
                f"FIM loss scope: {recorded} (from {args.train_split_file})",
                flush=True,
            )
            return str(recorded)
    print(
        "FIM loss scope: span (auto fallback; split file has no recorded scope)",
        flush=True,
    )
    return "span"


def _resolve_window_unit(args: argparse.Namespace) -> str:
    """Recover the training window policy before rebuilding exact eval samples."""
    requested = getattr(args, "window_unit", "auto")
    if requested != "auto":
        return str(requested)
    if args.train_split_file is not None:
        split = json.loads(args.train_split_file.read_text(encoding="utf-8"))
        recorded = split.get("window_unit")
        if recorded in WINDOW_UNITS:
            print(
                f"Window unit: {recorded} (from {args.train_split_file})",
                flush=True,
            )
            return str(recorded)
    print(
        "Window unit: byte_budget (auto fallback; split file has no recorded policy)",
        flush=True,
    )
    return "byte_budget"


def _verify_fixed_hole_replay(
    expected: dict[str, Any],
    meta: dict[str, Any],
    target_ids: list[int],
    window_key: tuple[str, int, int],
) -> None:
    actual = {
        "frame_lo": int(meta["frame_lo"]),
        "frame_hi": int(meta["frame_hi"]),
        "fim_split": int(meta["fim_split"]),
        "fim_gap": int(meta["fim_gap"]),
        "target_length": len(target_ids),
        "target_sha256": hashlib.sha256(bytes(target_ids)).hexdigest(),
    }
    mismatches = {
        key: (expected.get(key), value)
        for key, value in actual.items()
        if expected.get(key) != value
    }
    if mismatches:
        raise RuntimeError(
            f"Fixed-hole replay mismatch for {window_key}: {mismatches}. "
            "Use the same manifest, seed, window, and FIM settings as training."
        )


def _split_indices(
    dataset: ByteStreamWindowDataset, args: argparse.Namespace
) -> list[int]:
    all_indices = list(range(len(dataset)))
    if args.eval_split == "all":
        return all_indices
    if args.split_by_video:
        videos = sorted({str(s.h264_path) for s in dataset.samples})
        generator = torch.Generator().manual_seed(args.seed)
        perm = torch.randperm(len(videos), generator=generator).tolist()
        n_val = max(1, int(len(videos) * args.val_fraction))
        val_videos = {videos[i] for i in perm[:n_val]}
        if args.eval_split == "val":
            return [
                i
                for i, s in enumerate(dataset.samples)
                if str(s.h264_path) in val_videos
            ]
        return [
            i
            for i, s in enumerate(dataset.samples)
            if str(s.h264_path) not in val_videos
        ]

    val_size = max(1, int(len(dataset) * args.val_fraction))
    train_size = len(dataset) - val_size
    if train_size <= 0:
        raise RuntimeError("Need at least two usable windows for train/val split")
    generator = torch.Generator().manual_seed(args.seed)
    perm = torch.randperm(len(dataset), generator=generator).tolist()
    return perm[train_size:] if args.eval_split == "val" else perm[:train_size]


def _corrupt_gen_frame_hole_spec(
    dataset: ByteStreamWindowDataset,
    idx: int,
    *,
    corr_pos: float,
    eligibility_bytes: int,
    seed: int,
    frame_type: str = "any",
    gap_bytes: int | None = None,
) -> tuple[int, int, int, int] | None:
    """Compatibility wrapper returning only the selected corruption span."""

    hole, _reason = _corrupt_gen_frame_hole_spec_with_reason(
        dataset,
        idx,
        corr_pos=corr_pos,
        eligibility_bytes=eligibility_bytes,
        seed=seed,
        frame_type=frame_type,
        gap_bytes=gap_bytes,
    )
    return hole


def _corrupt_gen_frame_hole_spec_with_reason(
    dataset: ByteStreamWindowDataset,
    idx: int,
    *,
    corr_pos: float,
    eligibility_bytes: int,
    seed: int,
    frame_type: str = "any",
    gap_bytes: int | None = None,
) -> tuple[tuple[int, int, int, int] | None, str | None]:
    """Select one exact, byte-aligned corrupt_Gen-style frame deletion.

    ``ByteStreamWindowDataset`` has already been configured with a fixed
    ``fim_min_gap == fim_max_gap`` and the diagnostic's header guard. A returned
    span always has the full requested length; otherwise the reason explains why
    this window is ineligible instead of silently shortening the deletion.
    """
    if gap_bytes is None and dataset.fim_min_gap != dataset.fim_max_gap:
        raise ValueError("corrupt_gen_frame requires one fixed deletion length")
    gap = int(dataset.fim_min_gap if gap_bytes is None else gap_bytes)
    if not dataset.fim_min_gap <= gap <= dataset.fim_max_gap:
        raise ValueError(
            f"requested corruption length {gap} is outside the dataset range "
            f"[{dataset.fim_min_gap}, {dataset.fim_max_gap}]"
        )
    if eligibility_bytes < gap:
        raise ValueError("eligibility_bytes must be at least the corruption length")
    sample = dataset.samples[idx]
    data = sample.h264_path.read_bytes()
    candidates = dataset._fim_candidates(sample, data)
    if not candidates:
        return None, "no_fim_eligible_frame_boundary"

    if frame_type != "any":
        wanted = str(frame_type)
        candidates_by_type: dict[str, list[tuple[int, int]]] = {}
        for bounds in candidates:
            actual = _corruption_frame_type(dataset, idx, bounds[0], data=data)
            candidates_by_type.setdefault(actual, []).append(bounds)
        candidates = candidates_by_type.get(wanted, [])
        if not candidates:
            available = ",".join(
                f"{name}:{len(bounds)}"
                for name, bounds in sorted(candidates_by_type.items())
            )
            return (
                None,
                f"no_matching_frame_type(requested={wanted},available={available})",
            )

    sized_candidates = [
        (frame_lo, frame_hi)
        for frame_lo, frame_hi in candidates
        if frame_hi - (frame_lo + dataset.frame_guard_bytes) - 1 >= eligibility_bytes
    ]
    if not sized_candidates:
        max_available = max(
            frame_hi - (frame_lo + dataset.frame_guard_bytes) - 1
            for frame_lo, frame_hi in candidates
        )
        return (
            None,
            "frame_too_small("
            f"required={eligibility_bytes},max_available={max_available},"
            f"header_guard={dataset.frame_guard_bytes},frame_type={frame_type})",
        )

    candidates = sized_candidates

    # The seed is local to the window, so repeated checkpoint evaluations and
    # severity runs are reproducible without depending on DataLoader RNG state.
    rng = random.Random((int(seed) << 32) ^ int(idx))
    frame_lo, frame_hi = rng.choice(candidates)
    first_start = frame_lo + dataset.frame_guard_bytes
    available = frame_hi - first_start - gap
    if available < 0:
        raise AssertionError("eligible frame cannot hold the requested full cut")
    split = first_start + int(available * corr_pos)
    return (frame_lo, frame_hi, split, gap), None


def _log_sample_skip(
    dataset: ByteStreamWindowDataset,
    dataset_index: int,
    reason: str,
) -> None:
    """Emit one reproducible explanation for an excluded evaluation window."""

    sample = dataset.samples[dataset_index]
    print(
        "[sample-skip] "
        f"dataset_index={dataset_index} "
        f"path={sample.h264_path} "
        f"nals={sample.start_nal}:{sample.end_nal} "
        f"reason={reason}",
        flush=True,
    )


def _corruption_frame_type(
    dataset: ByteStreamWindowDataset,
    idx: int,
    frame_lo: int,
    *,
    data: bytes | None = None,
) -> str:
    """Return the first VCL slice class at a window-relative frame boundary."""
    sample = dataset.samples[idx]
    nals = dataset.nal_index[str(sample.h264_path)]
    if data is None:
        data = sample.h264_path.read_bytes()
    cursor = 0
    for nal in nals[sample.start_nal : sample.end_nal]:
        if cursor == frame_lo and nal.nal_type in VCL_NAL_TYPES:
            if nal.nal_type == 5:
                return "idr"
            nal_bytes = data[nal.start + nal.start_code_len : nal.end]
            try:
                rbsp, _byte_map, _epb = HS.unescape_rbsp(nal_bytes, 1, len(nal_bytes))
                reader = HS.BitReader(rbsp)
                reader.read_ue()  # first_mb_in_slice
                slice_type = reader.read_ue() % 5
            except (HS.BitReaderError, IndexError):
                return "unknown"
            return {
                0: "p",
                1: "b",
                2: "i",
                3: "sp",
                4: "si",
            }.get(slice_type, "unknown")
        cursor += nal.end - nal.start
    raise RuntimeError(
        f"No VCL NAL begins at frame_lo={frame_lo} for {sample.h264_path}"
    )


def _resolve_sample_policy(args: argparse.Namespace) -> EvalSamplePolicy:
    """Resolve every training-layout and corruption setting before loading data."""

    fim_loss_scope = _resolve_fim_loss_scope(
        args
    )  # str, "span" or "full". We use "full" most of the times
    window_unit = _resolve_window_unit(
        args
    )  # defines what the data sample looks like. We use one "GoP" as a sample.
    hole_placement = str(
        getattr(args, "hole_placement", "training_random")
    )  # "corrupt_gen_frame" for fixed corruption control / "training_random" for random corruption control
    corruption_lengths = _requested_corruption_lengths(args)
    if hole_placement == "corrupt_gen_frame":
        if not corruption_lengths or any(length <= 0 for length in corruption_lengths):
            raise ValueError("corrupt_gen_frame requires positive corruption lengths")
        min_gap = min(corruption_lengths)
        max_gap = max(corruption_lengths)
        frame_guard_bytes = int(getattr(args, "corr_header_guard_bytes", 4))
        eligibility_bytes = int(
            getattr(args, "corr_eligibility_bytes", None) or max_gap
        )
        if eligibility_bytes < max_gap:
            raise ValueError(
                "--corr-eligibility-bytes must be at least --corr-len-bytes"
            )
    elif hole_placement == "training_random":
        min_gap = int(args.fim_min_gap)
        max_gap = int(args.fim_max_gap)
        frame_guard_bytes = int(args.slice_header_guard_bytes)
        eligibility_bytes = max_gap
    else:
        raise ValueError(f"Unknown --hole-placement {hole_placement}")

    return EvalSamplePolicy(
        fim_loss_scope=fim_loss_scope,
        window_unit=window_unit,
        hole_placement=hole_placement,
        hole_set=str(getattr(args, "hole_set", "auto")),
        min_gap=min_gap,
        max_gap=max_gap,
        frame_guard_bytes=frame_guard_bytes,
        corruption_eligibility_bytes=eligibility_bytes,
    )


def _load_eval_dataset(
    args: argparse.Namespace,
    policy: EvalSamplePolicy,
) -> ByteStreamWindowDataset:
    """Load the manifest/index and rebuild the training-time window dataset."""

    rows = load_manifest_rows(
        args.manifest,
        max_rows=args.max_manifest_rows or None,
        report_progress=True,
    )
    index_path = args.nal_index_path or default_nal_index_path(args.manifest)
    nal_index = (
        load_nal_index(index_path, args.manifest, rows)
        if index_path.is_file()
        else None
    )
    if args.nal_index_path is not None and nal_index is None:
        raise FileNotFoundError(f"NAL index does not exist: {index_path}")

    return ByteStreamWindowDataset(
        rows,
        max_seq_length=args.max_window_bytes,
        min_frames=args.window_min_frames,
        p_fim=1.0,
        fim_format=args.fim_format,
        fim_loss_scope=policy.fim_loss_scope,
        use_eos=args.use_eos,
        fim_min_gap=policy.min_gap,
        fim_max_gap=policy.max_gap,
        frame_guard_bytes=policy.frame_guard_bytes,
        window_unit=policy.window_unit,
        resample_fim=False,
        nal_index=nal_index,
        seed=args.seed,
    )


def _select_eval_windows(
    args: argparse.Namespace,
    dataset: ByteStreamWindowDataset,
    policy: EvalSamplePolicy,
) -> tuple[list[int], FixedHoleMap]:
    """Select dataset windows using the recorded split or deterministic split logic."""

    fixed_holes: FixedHoleMap = {}
    if args.train_split_file is not None:
        split_metadata = json.loads(
            args.train_split_file.read_text(encoding="utf-8")
        )
        train_windows, train_videos, fixed_holes = _load_train_split(
            args.train_split_file
        )
        recorded_split_by_video = bool(split_metadata.get("split_by_video", False))
        if args.eval_split == "all":
            indices = list(range(len(dataset.samples)))
            split_desc = f"all {len(indices)} rebuilt windows"
        elif args.eval_split == "train":
            if train_windows:
                indices = [
                    index
                    for index, sample in enumerate(dataset.samples)
                    if (
                        str(sample.h264_path),
                        int(sample.start_nal),
                        int(sample.end_nal),
                    )
                    in train_windows
                ]
                split_desc = (
                    f"{len(indices)} exact train windows from {args.train_split_file}"
                )
            else:
                indices = [
                    index
                    for index, sample in enumerate(dataset.samples)
                    if str(sample.h264_path) in train_videos
                ]
                split_desc = (
                    f"{len(indices)} train videos from {args.train_split_file}"
                )
        else:
            if recorded_split_by_video:
                if not train_videos:
                    raise RuntimeError(
                        "train_split.json records split_by_video=true but contains "
                        "no training video identities"
                    )
                indices = [
                    index
                    for index, sample in enumerate(dataset.samples)
                    if str(sample.h264_path) not in train_videos
                ]
                if any(
                    str(dataset.samples[index].h264_path) in train_videos
                    for index in indices
                ):
                    raise AssertionError("validation videos overlap training videos")
                split_desc = (
                    f"{len(indices)} held-out video windows complementary to "
                    f"{args.train_split_file}"
                )
            else:
                if not train_windows:
                    raise RuntimeError(
                        "train_split.json contains no exact training windows; "
                        "cannot reconstruct a disjoint window-level validation set"
                    )
                indices = [
                    index
                    for index, sample in enumerate(dataset.samples)
                    if (
                        str(sample.h264_path),
                        int(sample.start_nal),
                        int(sample.end_nal),
                    )
                    not in train_windows
                ]
                if any(
                    (
                        str(dataset.samples[index].h264_path),
                        int(dataset.samples[index].start_nal),
                        int(dataset.samples[index].end_nal),
                    )
                    in train_windows
                    for index in indices
                ):
                    raise AssertionError("validation windows overlap training windows")
                split_desc = (
                    f"{len(indices)} held-out windows complementary to "
                    f"{args.train_split_file}"
                )
        if not indices:
            raise RuntimeError(
                f"No {args.eval_split} dataset windows matched -- check manifest, "
                "max rows, window settings, and train_split.json"
            )
        print(
            f"recorded-split filter: eval_split={args.eval_split} {split_desc}",
            flush=True,
        )
    else:
        indices = _split_indices(dataset, args)
        print(
            f"split filter: eval_split={args.eval_split} "
            f"selected {len(indices)}/{len(dataset)} windows",
            flush=True,
        )

    if policy.hole_placement == "corrupt_gen_frame":
        # Preserve the historical deterministic shuffle so severity sweeps select
        # the same source frames without clustering in the first manifest entries.
        indices = list(indices)
        random.Random(int(args.seed)).shuffle(indices)
        print(
            f"corrupt_gen_frame window order shuffled with seed={args.seed}",
            flush=True,
        )
    return indices, fixed_holes


def _resolve_hole_set(
    args: argparse.Namespace,
    policy: EvalSamplePolicy,
    fixed_holes: FixedHoleMap,
) -> EvalSamplePolicy:
    """Resolve auto/trained/heldout/sampled after inspecting recorded holes."""

    hole_set = policy.hole_set
    if policy.hole_placement == "corrupt_gen_frame":
        if hole_set not in ("auto", "sampled"):
            raise RuntimeError(
                "corrupt_gen_frame placement cannot replay trained or held-out "
                "random holes"
            )
        hole_set = "sampled"
    elif args.eval_split != "train":
        if hole_set == "trained":
            raise RuntimeError(
                "--hole-set trained is only valid with --eval-split train"
            )
        if hole_set == "auto":
            hole_set = "sampled"
    elif hole_set == "auto":
        hole_set = "trained" if fixed_holes else "sampled"

    if hole_set == "trained" and not fixed_holes:
        raise RuntimeError(
            "--hole-set trained requires cached fixed_fim_holes in train_split.json"
        )
    return replace(policy, hole_set=hole_set)


def _build_hole_requests(
    args: argparse.Namespace,
    dataset: ByteStreamWindowDataset,
    policy: EvalSamplePolicy,
    indices: list[int],
    fixed_holes: FixedHoleMap,
) -> list[HoleRequest]:
    """Choose exact corruption spans without yet constructing model tensors."""

    requests: list[HoleRequest] = []
    if policy.hole_placement == "corrupt_gen_frame":
        skip_reasons: Counter[str] = Counter()
        corruption_lengths = _requested_corruption_lengths(args)
        if getattr(args, "corr_len_bytes_list", None) is not None:
            # A severity schedule uses one distinct source window per length. Scan
            # the already shuffled split in order, carrying the cursor forward so
            # no clip is reused and each requested length appears exactly once.
            index_cursor = iter(indices)
            samples_per_length = int(args.corr_samples_per_length)
            for corruption_length in corruption_lengths:
                for replicate in range(samples_per_length):
                    selected = False
                    for index in index_cursor:
                        eligibility_bytes = int(
                            getattr(args, "corr_eligibility_bytes", None)
                            or corruption_length
                        )
                        hole, skip_reason = _corrupt_gen_frame_hole_spec_with_reason(
                            dataset,
                            index,
                            corr_pos=float(getattr(args, "corr_pos", 0.4)),
                            eligibility_bytes=eligibility_bytes,
                            seed=int(args.seed),
                            frame_type=str(getattr(args, "corr_frame_type", "any")),
                            gap_bytes=corruption_length,
                        )
                        if hole is None:
                            reason = skip_reason or "unknown_hole_selection_failure"
                            skip_reasons[reason] += 1
                            _log_sample_skip(dataset, index, reason)
                            continue
                        requests.append(HoleRequest(index, hole, None))
                        selected = True
                        break
                    if not selected:
                        raise RuntimeError(
                            "Could not select distinct eligible clip "
                            f"{replicate + 1}/{samples_per_length} for corruption "
                            f"length {corruption_length} bytes"
                        )
            print(
                "corrupt_gen_frame severity schedule: "
                + ", ".join(f"{length}B" for length in corruption_lengths)
                + f"; samples_per_length={samples_per_length}",
                flush=True,
            )
            if skip_reasons:
                print(
                    "Hole-selection skip summary: "
                    + ", ".join(
                        f"{reason}={count}"
                        for reason, count in sorted(skip_reasons.items())
                    ),
                    flush=True,
                )
            return requests

        corruption_length = corruption_lengths[0]
        for index in indices:
            hole, skip_reason = _corrupt_gen_frame_hole_spec_with_reason(
                dataset,
                index,
                corr_pos=float(getattr(args, "corr_pos", 0.4)),
                eligibility_bytes=policy.corruption_eligibility_bytes,
                seed=int(args.seed),
                frame_type=str(getattr(args, "corr_frame_type", "any")),
                gap_bytes=corruption_length,
            )
            if hole is None:
                reason = skip_reason or "unknown_hole_selection_failure"
                skip_reasons[reason] += 1
                _log_sample_skip(dataset, index, reason)
                continue
            requests.append(HoleRequest(index, hole, None))
        if skip_reasons:
            print(
                "Hole-selection skip summary: "
                + ", ".join(
                    f"{reason}={count}"
                    for reason, count in sorted(skip_reasons.items())
                ),
                flush=True,
            )
        return requests

    if policy.hole_set == "trained":
        indexed_holes: list[tuple[int, list[dict[str, Any]]]] = []
        for index in indices:
            sample = dataset.samples[index]
            key = (str(sample.h264_path), sample.start_nal, sample.end_nal)
            holes = fixed_holes.get(key)
            if not holes:
                raise RuntimeError(
                    f"Cached training holes are missing for train window: {key}"
                )
            indexed_holes.append((index, holes))

        # Round-robin by hole id, then window. NUM_CLIPS equal to the number of
        # windows therefore evaluates one hole per window before advancing to K=2.
        for hole_slot in range(max(len(holes) for _, holes in indexed_holes)):
            for index, holes in indexed_holes:
                if hole_slot >= len(holes):
                    continue
                expected = holes[hole_slot]
                requests.append(
                    HoleRequest(
                        index,
                        (
                            int(expected["frame_lo"]),
                            int(expected["frame_hi"]),
                            int(expected["fim_split"]),
                            int(expected["fim_gap"]),
                        ),
                        expected,
                    )
                )
        return requests

    if policy.hole_set == "heldout":
        for index in indices:
            sample = dataset.samples[index]
            key = (str(sample.h264_path), sample.start_nal, sample.end_nal)
            excluded = tuple(
                (
                    int(hole["frame_lo"]),
                    int(hole["frame_hi"]),
                    int(hole["fim_split"]),
                    int(hole["fim_gap"]),
                )
                for hole in fixed_holes.get(key, [])
            )
            for hole in dataset.heldout_fim_hole_specs(
                index,
                getattr(args, "heldout_holes_per_window", 1),
                exclude=excluded,
            ):
                requests.append(HoleRequest(index, hole, None))
        return requests

    return [HoleRequest(index, None, None) for index in indices]


def _materialize_fim_sample(
    args: argparse.Namespace,
    dataset: ByteStreamWindowDataset,
    policy: EvalSamplePolicy,
    request: HoleRequest,
) -> tuple[WindowFimSample | None, bool, str | None]:
    """Turn one hole request into the exact prompt, labels, and byte streams."""

    index = request.dataset_index
    expected = request.expected_training_hole
    item = (
        dataset[index]
        if request.hole_spec is None
        else dataset.fim_item_for_hole(
            index,
            request.hole_spec,
            hole_id=(int(expected.get("hole_id", 0)) if expected is not None else None),
        )
    )
    if item["sample_meta"].get("task") != "fim":
        return None, False, "dataset_item_is_not_fim"

    labels: Tensor = item["labels"]
    if not bool((labels != IGNORE_INDEX).any()):
        return None, False, "fim_item_has_no_supervised_labels"

    meta = item["sample_meta"]
    gap = int(meta["fim_gap"])
    split = int(meta["fim_split"])
    ar_labels = dataset.ar_item(index)["labels"]
    if dataset.use_eos:
        if int(ar_labels[-1]) != SEQ_EOS_ID:
            raise RuntimeError("window AR item is missing its configured SEQ_EOS")
        ar_labels = ar_labels[:-1]
    window_bytes = bytes(ar_labels.tolist())
    target_ids = list(window_bytes[split : split + gap])
    if len(target_ids) != gap or any(
        token < 0 or token >= BYTE_VOCAB_SIZE for token in target_ids
    ):
        return None, False, "missing_span_is_truncated_or_not_byte_tokens"

    # Generation starts immediately after FIM_END. Full-sequence supervision
    # starts earlier, so the prompt boundary must be derived from the known tail.
    target_token_count = gap + int(args.use_eos)
    prompt_end = item["input_ids"].numel() - target_token_count + 1
    if prompt_end <= 0:
        raise RuntimeError("invalid FIM prompt/target boundary")
    native_tail = labels[-target_token_count:]
    expected_tail = torch.tensor(
        target_ids + ([SEQ_EOS_ID] if args.use_eos else []),
        dtype=labels.dtype,
    )
    if not torch.equal(native_tail, expected_tail):
        raise RuntimeError(
            "FIM training labels do not end in the expected missing span; "
            "evaluation cannot preserve the training patch alignment"
        )

    window_key = (
        str(Path(meta["h264_path"])),
        int(meta["start_nal"]),
        int(meta["end_nal"]),
    )
    replay_verified = expected is not None
    if expected is not None:
        _verify_fixed_hole_replay(expected, meta, target_ids, window_key)

    sample = WindowFimSample(
        sample_index=index,
        h264_path=Path(meta["h264_path"]),
        start_nal=int(meta["start_nal"]),
        end_nal=int(meta["end_nal"]),
        frame_lo=int(meta["frame_lo"]),
        frame_hi=int(meta["frame_hi"]),
        split=int(meta["fim_split"]),
        gap=int(meta["fim_gap"]),
        prompt_ids=item["input_ids"][:prompt_end].clone(),
        prompt_region_ids=item["region_ids"][:prompt_end].clone(),
        prompt_offset_ids=item["offset_ids"][:prompt_end].clone(),
        teacher_input_ids=item["input_ids"].clone(),
        teacher_region_ids=item["region_ids"].clone(),
        teacher_offset_ids=item["offset_ids"].clone(),
        teacher_labels=item["labels"].clone(),
        target_bytes=bytes(target_ids),
        window_bytes=window_bytes,
        hole_id=(
            int(meta["fim_hole_id"]) if int(meta.get("fim_hole_id", -1)) >= 0 else None
        ),
        corruption_frame_type=(
            _corruption_frame_type(dataset, index, int(meta["frame_lo"]))
            if policy.hole_placement == "corrupt_gen_frame"
            else None
        ),
    )
    return sample, replay_verified, None


def _materialize_fim_samples(
    args: argparse.Namespace,
    dataset: ByteStreamWindowDataset,
    policy: EvalSamplePolicy,
    requests: list[HoleRequest],
) -> tuple[list[WindowFimSample], int]:
    """Materialize validated samples in request order up to --num-clips."""

    requested_count = (
        len(_requested_corruption_lengths(args)) * int(args.corr_samples_per_length)
        if getattr(args, "corr_len_bytes_list", None) is not None
        else args.num_clips
    )
    selected: list[WindowFimSample] = []
    verified_fixed_holes = 0
    skip_reasons: Counter[str] = Counter()
    for request in requests:
        sample, replay_verified, skip_reason = _materialize_fim_sample(
            args, dataset, policy, request
        )
        if sample is None:
            reason = skip_reason or "unknown_materialization_failure"
            skip_reasons[reason] += 1
            _log_sample_skip(dataset, request.dataset_index, reason)
            continue
        selected.append(sample)
        verified_fixed_holes += int(replay_verified)
        if len(selected) >= requested_count:
            break
    if skip_reasons:
        print(
            "Materialization skip summary: "
            + ", ".join(
                f"{reason}={count}" for reason, count in sorted(skip_reasons.items())
            ),
            flush=True,
        )
    if len(selected) < requested_count:
        print(
            "WARNING: requested "
            f"{requested_count} samples but selected {len(selected)}; "
            f"eligible_requests={len(requests)}",
            flush=True,
        )
    return selected, verified_fixed_holes


def _validate_sample_selection(selection: SampleSelection) -> None:
    """Reject empty selections and print reproducibility checks."""

    if not selection.samples:
        raise RuntimeError(
            "No FIM samples selected. Lower gap/guard constraints or check that "
            "window-FIM is reachable."
        )
    if selection.policy.hole_set == "trained":
        print(
            "Exact fixed training holes verified: "
            f"{selection.exact_training_holes_verified}/{len(selection.samples)}",
            flush=True,
        )
    elif selection.policy.hole_set == "heldout":
        print(
            "Held-out holes verified disjoint from cached training pool: "
            f"{len(selection.samples)}/{len(selection.samples)}",
            flush=True,
        )
    print(
        f"Selected {len(selection.samples)} FIM samples from "
        f"hole_set={selection.policy.hole_set} "
        f"placement={selection.policy.hole_placement}",
        flush=True,
    )


def build_eval_sample_selection(args: argparse.Namespace) -> SampleSelection:
    """Build evaluation samples as an explicit six-stage data pipeline."""

    print("[data 1/6] Resolve window and corruption policy", flush=True)
    policy = _resolve_sample_policy(args)

    print("[data 2/6] Load manifest, NAL index, and window dataset", flush=True)
    dataset = _load_eval_dataset(args, policy)

    print("[data 3/6] Select evaluation windows", flush=True)
    indices, fixed_holes = _select_eval_windows(args, dataset, policy)

    print("[data 4/6] Select trained, held-out, or sampled holes", flush=True)
    policy = _resolve_hole_set(args, policy, fixed_holes)
    requests = _build_hole_requests(args, dataset, policy, indices, fixed_holes)

    print("[data 5/6] Materialize FIM prompts, targets, and labels", flush=True)
    samples, verified_fixed_holes = _materialize_fim_samples(
        args, dataset, policy, requests
    )
    selection = SampleSelection(
        samples=samples,
        policy=policy,
        exact_training_holes_verified=verified_fixed_holes,
        fixed_training_holes_available=sum(
            len(holes) for holes in fixed_holes.values()
        ),
    )

    print("[data 6/6] Validate the final sample set", flush=True)
    _validate_sample_selection(selection)
    return selection


def _copy_selection_to_args(
    args: argparse.Namespace,
    selection: SampleSelection,
) -> None:
    """Maintain the legacy list-returning API for external callers and tests."""

    policy = selection.policy
    args.fim_loss_scope = policy.fim_loss_scope
    args.window_unit = policy.window_unit
    args.hole_set = policy.hole_set
    args.effective_fim_min_gap = policy.min_gap
    args.effective_fim_max_gap = policy.max_gap
    args.effective_frame_guard_bytes = policy.frame_guard_bytes
    args.effective_corr_eligibility_bytes = policy.corruption_eligibility_bytes
    args.exact_training_holes_verified = selection.exact_training_holes_verified
    args.fixed_training_holes_available = selection.fixed_training_holes_available


def build_eval_samples(args: argparse.Namespace) -> list[WindowFimSample]:
    """Compatibility wrapper returning only samples as the historical API did."""

    selection = build_eval_sample_selection(args)
    _copy_selection_to_args(args, selection)
    return selection.samples


def _sample_token(logits: Tensor, temperature: float, top_k: int, top_p: float) -> int:
    if temperature <= 0 and top_k <= 0 and top_p >= 1.0:
        return int(logits.argmax(dim=-1))
    logits = logits.float()
    if temperature > 0:
        logits = logits / temperature
    if top_k > 0:
        k = min(top_k, logits.numel())
        kth = torch.topk(logits, k).values[-1]
        logits = torch.where(
            logits < kth, torch.full_like(logits, float("-inf")), logits
        )
    if 0 < top_p < 1.0:
        sorted_logits, sorted_idx = torch.sort(logits, descending=True)
        probs = F.softmax(sorted_logits, dim=-1)
        cumulative = probs.cumsum(dim=-1)
        remove_sorted = cumulative > top_p
        remove_sorted[0] = False
        remove = torch.zeros_like(remove_sorted).scatter(0, sorted_idx, remove_sorted)
        logits = torch.where(remove, torch.full_like(logits, float("-inf")), logits)
    probs = F.softmax(logits, dim=-1)
    return int(torch.multinomial(probs, num_samples=1))


def _seed_parser_state(
    sample: WindowFimSample, *, slice_max_mbs: int | None
) -> HM.MaskState:
    """Build the H.264 state at the start of the missing span."""
    state = HM.MaskState(slice_max_mbs=slice_max_mbs, fail_closed=True)
    # Seed from ORIGINAL stream order. The PSM prompt contains model markers and
    # moves the orphan before generation, so prompt_ids are not parser input.
    for byte in sample.bytes_before_hole:
        HM.advance(state, byte)
    state.generation_started = True
    return state


def gt_parser_reconnects(sample: WindowFimSample, *, slice_max_mbs: int | None) -> bool:
    """Check that the automaton accepts the unmodified GT middle and suffix."""
    state = _seed_parser_state(sample, slice_max_mbs=slice_max_mbs)
    for byte in sample.target_bytes:
        allowed = HM.get_valid_byte_mask(state)
        if not allowed[byte]:
            return False
        HM.advance(state, byte)
        if state.automaton_unknown:
            return False
    return HM.can_append_bytes(state, sample.bytes_after_hole, require_complete=True)


def _termination_succeeded(stop_mode: str, stop_reason: str) -> bool | None:
    """Return autonomous termination success; oracle length has no such result."""
    if stop_mode == "learned_eos":
        return stop_reason == "eos"
    if stop_mode == "parser_reconnect":
        return stop_reason == "parser_reconnect"
    if stop_mode == "oracle_len":
        return None
    raise ValueError(f"unknown stop_mode: {stop_mode}")


@torch.inference_mode()
def generate_span(
    model: nn.Module,
    sample: WindowFimSample,
    device: torch.device,
    *,
    stop_mode: str,
    temperature: float,
    top_k: int,
    top_p: float,
    max_gen_bytes: int,
    mask_illegal_bytes: bool,
    slice_max_mbs: int | None,
) -> GenerationResult | None:
    raw = _unwrap_model(model)
    raw.eval()
    prompt = sample.prompt_ids.to(device).unsqueeze(0)
    region_ids = sample.prompt_region_ids.to(device).unsqueeze(0)
    offset_ids = sample.prompt_offset_ids.to(device).unsqueeze(0)
    prompt_len = prompt.size(1)
    supervised = (
        (sample.teacher_labels != IGNORE_INDEX).nonzero(as_tuple=False).flatten()
    )
    if not bool(supervised.numel()):
        return None
    supervision_start = int(supervised[0])
    if supervision_start >= prompt_len:
        raise RuntimeError("FIM supervision starts after the generation prompt")
    model_max_new = megabyte_max_new_bytes(
        raw,
        prompt_len,
        supervision_start=(
            supervision_start if int(raw.config.byte_patch_size) > 1 else None
        ),
    )
    if model_max_new <= 0:
        return None
    if stop_mode == "oracle_len":
        if sample.target_length > model_max_new:
            return None
        max_new = sample.target_length
    elif stop_mode in ("learned_eos", "parser_reconnect"):
        max_new = min(
            max_gen_bytes,
            model_max_new,
        )
    else:
        raise ValueError(f"unknown stop_mode: {stop_mode}")
    if max_new <= 0:
        return None

    parser_state: HM.MaskState | None = None
    if mask_illegal_bytes or stop_mode == "parser_reconnect":
        parser_state = _seed_parser_state(sample, slice_max_mbs=slice_max_mbs)

    megabyte = None
    if int(raw.config.byte_patch_size) > 1:
        megabyte = MegabyteInference(
            raw,
            prompt,
            region_ids,
            offset_ids,
            device,
            supervision_start=supervision_start,
        )
    else:
        cache_dtype = (
            torch.bfloat16 if device.type == "cuda" else next(raw.parameters()).dtype
        )
        raw.set_kv_cache(
            batch_size=1,
            max_seq_length=raw.max_seq_length,
            device=device,
            dtype=cache_dtype,
        )
    generated: list[int] = []
    eos_stopped = False
    stop_reason = "budget"
    mask_argmax_rejected = 0
    mask_eos_checks = 0
    mask_eos_blocked = 0
    mask_probability_mass_sum = 0.0
    mask_probability_mass_count = 0
    first_mask_intervention: dict[str, Any] | None = None
    parser_reconnect_checks = 0
    parser_reconnect_found = False
    try:
        if megabyte is None:
            with torch.autocast(
                device_type=device.type,
                dtype=torch.bfloat16,
                enabled=device.type == "cuda",
            ):
                logits = raw(
                    prompt,
                    input_pos=torch.arange(prompt_len, device=device, dtype=torch.long),
                    input_pos_maxp1=prompt_len,
                    region_ids=region_ids,
                    offset_ids=offset_ids,
                )
        for generated_idx in range(max_new):
            next_logits = (
                megabyte.next_logits()[0] if megabyte is not None else logits[0, -1]
            )
            byte_logits = next_logits[:BYTE_VOCAB_SIZE].clone()
            if mask_illegal_bytes:
                assert parser_state is not None
                allowed = HM.get_valid_byte_mask(parser_state)
                if not any(allowed):
                    stop_reason = "mask_boxed_in"
                    break
                raw_byte_argmax = int(next_logits[:BYTE_VOCAB_SIZE].argmax(dim=-1))
                if not allowed[raw_byte_argmax]:
                    mask_argmax_rejected += 1
                    if first_mask_intervention is None:
                        auto = parser_state.automaton
                        first_mask_intervention = {
                            "generated_byte": generated_idx,
                            "nal_index": parser_state.nal_index,
                            "model_argmax": raw_byte_argmax,
                            "stage": (
                                "nal_header"
                                if parser_state.expect_nal_header
                                else getattr(auto, "stage", "unknown")
                            ),
                            "syntax": (
                                "nal_header"
                                if parser_state.expect_nal_header
                                else getattr(auto, "ae_tag", "unknown")
                            ),
                        }
                allowed_tensor = torch.tensor(
                    allowed, dtype=torch.bool, device=byte_logits.device
                )
                log_total = torch.logsumexp(
                    next_logits[:BYTE_VOCAB_SIZE].float(), dim=0
                )
                log_allowed = torch.logsumexp(
                    next_logits[:BYTE_VOCAB_SIZE][allowed_tensor].float(), dim=0
                )
                mask_probability_mass_sum += float(
                    torch.exp(log_allowed - log_total).item()
                )
                mask_probability_mass_count += 1
                byte_logits[~allowed_tensor] = float("-inf")

            if stop_mode == "learned_eos":
                eos_allowed = parser_state is None
                if parser_state is not None:
                    # For greedy decoding, avoid the suffix probe unless EOS can
                    # actually beat the best legal byte. Sampling must know the full
                    # support, so it always performs the check.
                    sampling = not (temperature <= 0 and top_k <= 0 and top_p >= 1.0)
                    best_byte = byte_logits.max()
                    eos_competitive = bool(
                        sampling
                        or not torch.isfinite(best_byte)
                        or next_logits[SEQ_EOS_ID] >= best_byte
                    )
                    if eos_competitive:
                        mask_eos_checks += 1
                        eos_allowed = HM.can_append_bytes(
                            parser_state,
                            sample.bytes_after_hole,
                            require_complete=True,
                        )
                        if not eos_allowed:
                            mask_eos_blocked += 1
                eos_logit = next_logits[SEQ_EOS_ID : SEQ_EOS_ID + 1].clone()
                if not eos_allowed:
                    eos_logit.fill_(float("-inf"))
                allowed_logits = torch.cat((byte_logits, eos_logit))
                if not torch.isfinite(allowed_logits).any():
                    stop_reason = "mask_boxed_in"
                    break
                token = _sample_token(allowed_logits, temperature, top_k, top_p)
                token = SEQ_EOS_ID if token == BYTE_VOCAB_SIZE else token
                if token == SEQ_EOS_ID:
                    eos_stopped = True
                    stop_reason = "eos"
                    break
            else:
                if not torch.isfinite(byte_logits).any():
                    stop_reason = "mask_boxed_in"
                    break
                token = _sample_token(byte_logits, temperature, top_k, top_p)

            if token < 0 or token >= BYTE_VOCAB_SIZE:
                stop_reason = f"invalid_token_{token}"
                break
            generated.append(token)
            if parser_state is not None:
                HM.advance(parser_state, token)
            if stop_mode == "parser_reconnect":
                assert parser_state is not None
                parser_reconnect_checks += 1
                if HM.can_append_bytes(
                    parser_state,
                    sample.bytes_after_hole,
                    require_complete=True,
                ):
                    parser_reconnect_found = True
                    stop_reason = "parser_reconnect"
                    break
            if generated_idx == max_new - 1:
                stop_reason = "oracle_len" if stop_mode == "oracle_len" else "budget"
                break

            if megabyte is not None:
                megabyte.append(token, REGION_BRIDGE, generated_idx + 1)
                continue
            position = prompt_len + generated_idx
            with torch.autocast(
                device_type=device.type,
                dtype=torch.bfloat16,
                enabled=device.type == "cuda",
            ):
                logits = raw(
                    torch.tensor([[token]], device=device, dtype=torch.long),
                    input_pos=torch.tensor([position], device=device, dtype=torch.long),
                    input_pos_maxp1=position + 1,
                    region_ids=torch.tensor(
                        [[REGION_BRIDGE]], device=device, dtype=torch.long
                    ),
                    offset_ids=torch.tensor(
                        [[generated_idx + 1]], device=device, dtype=torch.long
                    ),
                )
    finally:
        if megabyte is not None:
            megabyte.close()
        else:
            raw.clear_kv_cache()
    return GenerationResult(
        bytes(generated),
        eos_stopped,
        stop_reason,
        len(generated),
        parser_reconnect_checks=parser_reconnect_checks,
        parser_reconnect_found=parser_reconnect_found,
        parser_failure_reason=(
            parser_state.failure_reason if parser_state is not None else None
        ),
        mask_calls=(
            parser_state.mask_calls
            if mask_illegal_bytes and parser_state is not None
            else 0
        ),
        mask_strict_calls=(
            parser_state.strict_mask_calls
            if mask_illegal_bytes and parser_state is not None
            else 0
        ),
        mask_permissive_calls=(
            parser_state.permissive_mask_calls
            if mask_illegal_bytes and parser_state is not None
            else 0
        ),
        mask_argmax_rejected=mask_argmax_rejected,
        mask_eos_checks=mask_eos_checks,
        mask_eos_blocked=mask_eos_blocked,
        mask_failure_reason=(
            parser_state.failure_reason
            if mask_illegal_bytes and parser_state is not None
            else None
        ),
        mask_probability_mass_sum=mask_probability_mass_sum,
        mask_probability_mass_count=mask_probability_mass_count,
        first_mask_intervention=first_mask_intervention,
    )


def _teacher_forced_span_mask(labels: Tensor, target_length: int) -> Tensor | None:
    """Select the missing bytes and optional EOS from native patched labels."""
    supervised_positions = (labels != IGNORE_INDEX).nonzero(as_tuple=False)
    if not bool(supervised_positions.numel()):
        return None
    last_label = int(labels[tuple(supervised_positions[-1].tolist())])
    span_token_count = target_length + int(last_label == SEQ_EOS_ID)
    if supervised_positions.size(0) < span_token_count or span_token_count <= 0:
        return None
    metric_positions = supervised_positions[-span_token_count:]
    metric_mask = torch.zeros_like(labels, dtype=torch.bool)
    metric_mask[tuple(metric_positions.T)] = True
    return metric_mask


@torch.inference_mode()
def teacher_forced_span_metrics(
    model: nn.Module,
    sample: WindowFimSample,
    device: torch.device,
) -> dict[str, Any] | None:
    """Score the FIM span without changing its training-time patch alignment."""
    raw = _unwrap_model(model)
    raw.eval()
    patch_size = int(raw.config.byte_patch_size)
    if patch_size > 1:
        patched = megabyte_teacher_forced_sample(
            sample.teacher_input_ids,
            sample.teacher_labels,
            sample.teacher_region_ids,
            sample.teacher_offset_ids,
            patch_size,
        )
        if patched["input_ids"].size(1) > raw.max_seq_length:
            return None
        idx = patched["input_ids"].to(device)
        labels = patched["labels"].to(device)
        region_ids = patched["region_ids"].to(device)
        offset_ids = patched["offset_ids"].to(device)
        model_kwargs = {"patch_targets": labels}
    else:
        if sample.teacher_input_ids.numel() > raw.max_seq_length:
            return None
        idx = sample.teacher_input_ids.to(device).unsqueeze(0)
        labels = sample.teacher_labels.to(device).unsqueeze(0)
        region_ids = sample.teacher_region_ids.to(device).unsqueeze(0)
        offset_ids = sample.teacher_offset_ids.to(device).unsqueeze(0)
        model_kwargs = {}
    with torch.autocast(
        device_type=device.type,
        dtype=torch.bfloat16,
        enabled=device.type == "cuda",
    ):
        logits = raw(
            idx,
            region_ids=region_ids,
            offset_ids=offset_ids,
            **model_kwargs,
        )
    metric_mask = _teacher_forced_span_mask(labels, sample.target_length)
    if metric_mask is None:
        return None
    native_mask = labels != IGNORE_INDEX
    native_labels = labels[native_mask]
    # Full-sequence FIM training supervises every serialized transition, but the
    # reported metric is intentionally hole-only. Select the final missing+EOS
    # positions from the *training-aligned* forward pass instead of rebuilding a
    # span-only sample (which resets the MEGABYTE patch phase).
    supervised_labels = labels[metric_mask]
    pred = logits.argmax(dim=-1)[metric_mask]
    byte_mask = supervised_labels < BYTE_VOCAB_SIZE
    eos_mask = supervised_labels == SEQ_EOS_ID
    byte_total = int(byte_mask.sum())
    eos_total = int(eos_mask.sum())
    byte_correct = (
        int((pred[byte_mask] == supervised_labels[byte_mask]).sum())
        if byte_total
        else 0
    )
    eos_correct = int((pred[eos_mask] == SEQ_EOS_ID).sum()) if eos_total else 0
    loss = F.cross_entropy(logits[metric_mask], supervised_labels)
    native_loss = F.cross_entropy(logits[native_mask], native_labels)
    element_correct: dict[str, list[int]] = {}
    element_legal: dict[str, list[int]] = {}
    element_illegal_different: dict[str, list[int]] = {}
    if byte_total == sample.target_length:
        try:
            spans = HS.parse_stream(
                sample.gt_truncated_stream, parse_slice_data=True
            ).all_spans()
            gt_list = list(sample.target_bytes)
            pred_list = [int(x) for x in pred[byte_mask].detach().cpu().tolist()]
            (
                element_correct,
                element_legal,
                element_illegal_different,
            ) = AR._value_legal_hits(
                spans,
                sample.split,
                sample.split + sample.target_length,
                gt_list,
                pred_list,
            )
        except Exception:
            # The strict decoder/parser diagnostics below remain authoritative. A
            # failed optional TF attribution must not discard the sample.
            pass
    return {
        "tf_ce_nats": float(loss),
        "tf_native_ce_nats": float(native_loss),
        "tf_native_target_tokens": int(native_labels.numel()),
        "tf_target_tokens": int(supervised_labels.numel()),
        "tf_byte_total": byte_total,
        "tf_byte_correct": byte_correct,
        "tf_byte_acc": byte_correct / max(byte_total, 1),
        "tf_eos_total": eos_total,
        "tf_eos_correct": eos_correct,
        "tf_eos_acc": eos_correct / max(eos_total, 1) if eos_total else None,
        "element_correct_counts": element_correct,
        "syntax_legal_counts": element_legal,
        "syntax_illegal_when_different_counts": element_illegal_different,
    }


_INDEX_RE = re.compile(r"\[\d+\]")


def repaired_stream_diagnostics(
    stream: bytes, generated_start: int, generated_length: int
) -> dict[str, Any]:
    """Locate the first syntax failure and count generated bytes before it.

    A generated span is not required to match GT. It survives until the repaired
    stream's own parser state first becomes inconsistent. If failure is discovered
    in the fixed suffix, all generated bytes were consumed, but decode success can
    still be false because the generated state did not reconnect to that suffix.
    """
    try:
        parsed = HS.parse_stream(stream, parse_slice_data=True)
    except Exception as exc:  # defensive: parser diagnostics should not kill eval
        return {
            "parse_ok": False,
            "parse_error": type(exc).__name__,
            "nals": 0,
            "completed_bytes": 0,
            "desync_region": "unknown",
            "desync_category": "unknown",
            "desync_reason": type(exc).__name__,
            "first_desync": generated_start,
        }
    statuses = [getattr(n.status, "name", str(n.status)) for n in parsed.nals]
    bad = next((n for n in parsed.nals if n.status != HS.ParseStatus.OK), None)
    first_desync: int | None = None
    region = "none"
    category = "none"
    reason = "none"
    failure_context = None
    if bad is not None:
        first_desync = (
            bad.desync_byte if bad.desync_byte is not None else bad.nal.payload_end
        )
        reason = bad.reason_kind or getattr(bad.status, "name", str(bad.status))
        failure_context = bad.failure_context
        if bad.failure_element:
            region = _INDEX_RE.sub("", bad.failure_element)
        selected_span = bad.spans[-1] if bad.spans else None
        if bad.desync_bit is not None and bad.spans:
            prior = [s for s in bad.spans if s.bit_start <= bad.desync_bit]
            if prior:
                selected_span = prior[-1]
        if region == "none" and selected_span is not None:
            region = _INDEX_RE.sub("", selected_span.name)
        if isinstance(failure_context, dict) and failure_context.get("category"):
            category = str(failure_context["category"])
        elif selected_span is not None:
            category = selected_span.category.value

    if first_desync is None:
        completed = generated_length
    else:
        completed = max(
            0, min(generated_length, int(first_desync) - int(generated_start))
        )
    return {
        "parse_ok": bad is None,
        "parse_status_hist": {s: statuses.count(s) for s in sorted(set(statuses))},
        "nals": len(parsed.nals),
        "completed_bytes": completed,
        "desync_region": region,
        "desync_category": category,
        "desync_reason": reason,
        "first_desync": first_desync,
        "failure_context": failure_context,
    }


