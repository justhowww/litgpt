"""Clean-prefix continuation probe for the multi-frame AR model (H0).

Verifies the AVC-LM/JPEG-LM generation legacy on *our* setup: give the model the
first N frames of a stream window as a clean prefix, free-run generate the next M
frames (byte-by-byte, external frame-count stop -- the AR model has no learned
EOS), strict-decode the result, and compare the generated continuation to the
ground-truth continuation.

H0 pass = decode-valid + plausible continuation; PSNR/SSIM vs GT is secondary
(the model invents a plausible-but-different future, so low PSNR is expected even
for good generation). The headline signal is the validity rate + the side-by-side
GT-vs-model continuation video.

Usage:
    python scripts/byte/eval/eval_stream_continuation.py MANIFEST \
        --checkpoint-dirs RUN/step-XXXX [...] --out-dir OUT \
        --prefix-frames 8 --cont-frames 4 --num-clips 20
"""

from __future__ import annotations

import argparse
import csv
import json
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import torch
from torch import Tensor

_REPO_ROOT = Path(__file__).resolve().parents[3]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from litgpt.byte.data import (  # noqa: E402
    BYTE_VOCAB_SIZE,
    PARAMETER_SET_NAL_TYPES,
    REGION_META,
    REGION_TARGET,
    SLICE_BOS_ID,
    VCL_NAL_TYPES,
    NALUnit,
    bytes_to_ids,
    default_nal_index_path,
    load_manifest_rows,
    load_nal_index,
)
from litgpt.byte.reconstruction import image_psnr, image_ssim, parse_ppm  # noqa: E402
from scripts.byte.eval.eval_checkpoints import jsonable, load_model, save_png  # noqa: E402

PSNR_PERFECT_CAP = 100.0
START_CODE = (0, 0, 1)


@dataclass
class ContinuationClip:
    h264_path: Path
    prefix_end_nal: int  # exclusive: NALs [0:prefix_end_nal] form the clean prefix
    cont_end_nal: int  # exclusive: NALs [0:cont_end_nal] are the GT prefix+continuation
    prefix_frames: int
    cont_frames: int


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("manifest", type=Path)
    parser.add_argument("--nal-index-path", type=Path, default=None)
    parser.add_argument("--checkpoint-dirs", type=Path, nargs="+", required=True)
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--device", default="cuda")
    parser.add_argument("--max-manifest-rows", type=int, default=0)
    parser.add_argument("--num-clips", type=int, default=20)
    parser.add_argument("--num-visualizations", type=int, default=8)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--prefix-frames", type=int, default=8, help="N clean frames given to the model.")
    parser.add_argument("--cont-frames", type=int, default=4, help="M frames the model must generate.")
    parser.add_argument("--max-window-bytes", type=int, default=16384, help="Byte budget for prefix+continuation packing.")
    parser.add_argument("--max-gen-multiple", type=float, default=2.0, help="Cap generated bytes at this multiple of the GT continuation length.")
    parser.add_argument(
        "--eval-intra",
        action="store_true",
        default=True,
        help="Also run intra (I-frame) generation: prompt = the parameter sets "
        "before an IDR, generate the IDR from scratch (the H.264 analog of JPEG-LM "
        "intra generation). Reported separately as mode=intra.",
    )
    parser.add_argument("--no-eval-intra", dest="eval_intra", action="store_false")
    parser.add_argument("--temperature", type=float, default=0.0, help="0 = greedy.")
    parser.add_argument("--viz-fps", type=int, default=6)
    parser.add_argument("--ffmpeg-binary", default="ffmpeg")
    parser.add_argument("--timeout-sec", type=int, default=60)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if args.prefix_frames < 1 or args.cont_frames < 1:
        raise SystemExit("--prefix-frames and --cont-frames must be positive")
    args.out_dir.mkdir(parents=True, exist_ok=True)
    device = torch.device(args.device if torch.cuda.is_available() or args.device == "cpu" else "cpu")

    rows = load_manifest_rows(
        args.manifest, max_rows=args.max_manifest_rows or None, report_progress=True
    )
    index_path = args.nal_index_path or default_nal_index_path(args.manifest)
    nal_index = load_nal_index(index_path, args.manifest, rows)

    clips = select_continuation_clips(rows, nal_index, args)
    print(f"Selected {len(clips)} continuation clips", flush=True)
    if not clips:
        raise SystemExit("No clips with enough frames; lower --prefix-frames/--cont-frames or raise --max-window-bytes")
    intra_clips = select_intra_clips(rows, nal_index, args) if args.eval_intra else []
    if args.eval_intra:
        print(f"Selected {len(intra_clips)} intra (I-frame) clips", flush=True)

    (args.out_dir / "config.json").write_text(
        json.dumps(jsonable(vars(args)), indent=2) + "\n", encoding="utf-8"
    )

    metrics_path = args.out_dir / "metrics.jsonl"
    details_path = args.out_dir / "clip_details.jsonl"
    summaries: list[dict[str, Any]] = []
    for checkpoint_dir in args.checkpoint_dirs:
        name = checkpoint_dir.name
        print(f"Loading checkpoint: {checkpoint_dir}", flush=True)
        model = load_model(checkpoint_dir, device)
        frame_dir = args.out_dir / "frames" / name
        frame_dir.mkdir(parents=True, exist_ok=True)
        for mode, mode_clips in (("continuation", clips), ("intra", intra_clips)):
            if not mode_clips:
                continue
            summary, details, viz = evaluate_checkpoint(model, mode_clips, nal_index, args, device, name, mode)
            summaries.append(summary)
            save_continuation_videos(viz, frame_dir, name, args, tag=mode)
            append_jsonl(metrics_path, [summary])
            append_jsonl(details_path, details)
            print(json.dumps(summary, indent=2), flush=True)
        del model

    write_summary_csv(args.out_dir / "summary.csv", summaries)
    print(f"Continuation evaluation complete: {args.out_dir}", flush=True)


def select_continuation_clips(
    rows: list[dict[str, Any]], nal_index: dict[str, list[NALUnit]], args: argparse.Namespace
) -> list[ContinuationClip]:
    import random

    rng = random.Random(args.seed)
    candidate_rows = list(rows)
    rng.shuffle(candidate_rows)
    needed = args.prefix_frames + args.cont_frames
    clips: list[ContinuationClip] = []
    for row in candidate_rows:
        path = Path(row["h264_path"])
        nals = nal_index[str(path)]
        clip = _first_qualifying_window(path, nals, needed, args.max_window_bytes, args.prefix_frames)
        if clip is not None:
            clips.append(clip)
        if len(clips) >= args.num_clips:
            break
    return clips


def _first_qualifying_window(
    path: Path, nals: list[NALUnit], needed_frames: int, max_bytes: int, prefix_frames: int
) -> ContinuationClip | None:
    """First IDR-anchored window holding >= needed_frames VCL frames within budget."""
    n = len(nals)
    for k in range(n):
        if nals[k].nal_type != 5:
            continue
        start = k
        while start - 1 >= 0 and nals[start - 1].nal_type in PARAMETER_SET_NAL_TYPES:
            start -= 1
        total = 0
        vcl = 0
        prefix_end = -1
        cont_end = -1
        end = start
        while end < n:
            nal_len = nals[end].end - nals[end].start
            if total + nal_len > max_bytes:
                break
            total += nal_len
            if nals[end].nal_type in VCL_NAL_TYPES:
                vcl += 1
                if vcl == prefix_frames:
                    prefix_end = end + 1
                if vcl == needed_frames:
                    cont_end = end + 1
                    break
            end += 1
        if cont_end > 0 and prefix_end > 0:
            return ContinuationClip(
                path, prefix_end, cont_end, prefix_frames, needed_frames - prefix_frames
            )
    return None


def select_intra_clips(
    rows: list[dict[str, Any]], nal_index: dict[str, list[NALUnit]], args: argparse.Namespace
) -> list[ContinuationClip]:
    """Intra (I-frame) generation: prompt = the parameter sets preceding the first
    IDR, model generates the IDR from scratch. prefix_frames=0, cont_frames=1."""
    import random

    rng = random.Random(args.seed + 1)
    candidate_rows = list(rows)
    rng.shuffle(candidate_rows)
    clips: list[ContinuationClip] = []
    for row in candidate_rows:
        path = Path(row["h264_path"])
        nals = nal_index[str(path)]
        idr = next((k for k, nal in enumerate(nals) if nal.nal_type == 5), None)
        if idr is None:
            continue
        start = idr
        while start - 1 >= 0 and nals[start - 1].nal_type in PARAMETER_SET_NAL_TYPES:
            start -= 1
        if start == idr:
            continue  # no SPS/PPS before the IDR -> cannot decode the generated frame
        psp = sum(nals[i].end - nals[i].start for i in range(start, idr))
        idr_len = nals[idr].end - nals[idr].start
        if psp + idr_len > args.max_window_bytes:
            continue
        clips.append(ContinuationClip(path, prefix_end_nal=idr, cont_end_nal=idr + 1, prefix_frames=0, cont_frames=1))
        if len(clips) >= args.num_clips:
            break
    return clips


def evaluate_checkpoint(
    model: torch.nn.Module,
    clips: list[ContinuationClip],
    nal_index: dict[str, list[NALUnit]],
    args: argparse.Namespace,
    device: torch.device,
    checkpoint_name: str,
    mode: str = "continuation",
) -> tuple[dict[str, Any], list[dict[str, Any]], dict[int, dict[str, Any]]]:
    decode_ok = 0
    full_count = 0
    cont_psnr: list[float] = []
    cont_ssim: list[float] = []
    frames_made: list[int] = []
    details: list[dict[str, Any]] = []
    viz: dict[int, dict[str, Any]] = {}

    for clip_idx, clip in enumerate(clips):
        print(f"  {checkpoint_name}: clip {clip_idx + 1}/{len(clips)}", flush=True)
        data = clip.h264_path.read_bytes()
        nals = nal_index[str(clip.h264_path)]
        prefix_bytes = _concat_nals(data, nals, 0, clip.prefix_end_nal)
        gt_bytes = _concat_nals(data, nals, 0, clip.cont_end_nal)
        gt_cont_len = len(gt_bytes) - len(prefix_bytes)

        gt_frames, _ = decode_h264(gt_bytes, args, strict=False)
        if len(gt_frames) < clip.prefix_frames + clip.cont_frames:
            details.append({"checkpoint": checkpoint_name, "clip_index": clip_idx, "status": "gt_decode_short"})
            continue

        max_gen = min(int(gt_cont_len * args.max_gen_multiple) + 512, model_max_gen(model, prefix_bytes))
        gen_bytes, gen_frames_emitted = generate_continuation(
            model, prefix_bytes, nals, clip.prefix_end_nal, device, args, clip.cont_frames, max_gen
        )
        model_bytes = prefix_bytes + gen_bytes
        model_frames, model_status = decode_h264(model_bytes, args, strict=True)
        if not model_frames:
            model_frames, model_status = decode_h264(model_bytes, args, strict=False)

        n, m = clip.prefix_frames, clip.cont_frames
        produced = max(0, len(model_frames) - n)
        frames_made.append(produced)
        strict_valid = model_status == "decoded" and len(model_frames) >= n + m
        decode_ok += int(model_status == "decoded")
        full_count += int(strict_valid)

        clip_psnr: list[float] = []
        clip_ssim: list[float] = []
        for t in range(n, n + m):
            if t < len(model_frames) and t < len(gt_frames) and model_frames[t].shape == gt_frames[t].shape:
                p = image_psnr(gt_frames[t], model_frames[t])
                clip_psnr.append(PSNR_PERFECT_CAP if p == float("inf") else p)
                clip_ssim.append(image_ssim(gt_frames[t], model_frames[t]))
        cont_psnr.extend(clip_psnr)
        cont_ssim.extend(clip_ssim)

        details.append({
            "checkpoint": checkpoint_name,
            "clip_index": clip_idx,
            "h264_path": str(clip.h264_path),
            "status": model_status,
            "frames_generated": produced,
            "frames_target": m,
            "start_codes_emitted": gen_frames_emitted,
            "strict_valid": strict_valid,
            "gen_bytes": len(gen_bytes),
            "gt_cont_bytes": gt_cont_len,
            "cont_psnr_mean": mean(clip_psnr),
            "cont_ssim_mean": mean(clip_ssim),
        })
        if clip_idx < args.num_visualizations:
            viz[clip_idx] = {
                "gt_frames": [f.cpu() for f in gt_frames[: n + m]],
                "model_frames": [f.cpu() for f in model_frames[: n + m]],
                "prefix_frames": n,
                "h264_path": str(clip.h264_path),
            }

    attempted = len(clips)
    summary = {
        "checkpoint": checkpoint_name,
        "mode": mode,
        "num_clips": attempted,
        "decode_rate": decode_ok / attempted if attempted else 0.0,
        "full_continuation_rate": full_count / attempted if attempted else 0.0,
        "frames_generated_mean": mean(frames_made),
        "frames_target": clips[0].cont_frames if clips else 0,
        "cont_psnr_mean": mean(cont_psnr),
        "cont_ssim_mean": mean(cont_ssim),
        "prefix_frames": clips[0].prefix_frames if clips else 0,
        "temperature": args.temperature,
    }
    return summary, details, viz


def model_max_gen(model: torch.nn.Module, prefix_bytes: bytes) -> int:
    raw = model.module if hasattr(model, "module") else model
    return max(0, int(raw.max_seq_length) - len(prefix_bytes) - 1)


def generate_continuation(
    model: torch.nn.Module,
    prefix_bytes: bytes,
    nals: list[NALUnit],
    prefix_end_nal: int,
    device: torch.device,
    args: argparse.Namespace,
    cont_frames: int,
    max_gen: int,
) -> tuple[bytes, int]:
    """Free-run byte generation, stopping after the model emits cont_frames complete
    frames (cont_frames + 1 start codes) or the byte budget. Offsets reset per NAL by
    detecting start codes; region is REGION_TARGET for all generated bytes."""
    raw = model.module if hasattr(model, "module") else model
    raw.eval()

    prompt_ids, prompt_region, prompt_offset = _prompt_tensors(prefix_bytes, nals, prefix_end_nal)
    prompt_ids = prompt_ids.to(device).unsqueeze(0)
    prompt_region = prompt_region.to(device).unsqueeze(0)
    prompt_offset = prompt_offset.to(device).unsqueeze(0)
    prompt_len = prompt_ids.size(1)
    if max_gen <= 0:
        return b"", 0

    cache_dtype = torch.bfloat16 if device.type == "cuda" else next(raw.parameters()).dtype
    raw.set_kv_cache(batch_size=1, max_seq_length=raw.max_seq_length, device=device, dtype=cache_dtype)
    generated: list[int] = []
    start_codes = 0
    gen_offset = 0  # first generated byte is offset 0 of frame N's NAL
    try:
        with torch.autocast(device_type=device.type, dtype=torch.bfloat16, enabled=device.type == "cuda"):
            logits = raw(
                prompt_ids,
                input_pos=torch.arange(prompt_len, device=device),
                input_pos_maxp1=prompt_len,
                region_ids=prompt_region,
                offset_ids=prompt_offset,
            )
        for step in range(max_gen):
            next_logits = logits[:, -1, :BYTE_VOCAB_SIZE]
            if args.temperature <= 0:
                token = int(next_logits.argmax(dim=-1))
            else:
                probs = torch.softmax(next_logits.float() / args.temperature, dim=-1)
                token = int(torch.multinomial(probs, 1))
            generated.append(token)

            is_start = len(generated) >= 3 and tuple(generated[-3:]) == START_CODE
            token_offset = gen_offset
            if is_start:
                start_codes += 1
                if start_codes == cont_frames + 1:
                    generated = generated[:-3]  # drop the partial next frame
                    break
                gen_offset = 3  # next byte is the header of the new NAL
            else:
                gen_offset = token_offset + 1
            if step == max_gen - 1:
                break

            position = prompt_len + step
            with torch.autocast(device_type=device.type, dtype=torch.bfloat16, enabled=device.type == "cuda"):
                logits = raw(
                    torch.tensor([[token]], device=device),
                    input_pos=torch.tensor([position], device=device),
                    input_pos_maxp1=position + 1,
                    region_ids=torch.full((1, 1), REGION_TARGET, device=device, dtype=torch.long),
                    offset_ids=torch.full((1, 1), token_offset, device=device, dtype=torch.long),
                )
    finally:
        raw.clear_kv_cache()
    return bytes(generated), start_codes


def _prompt_tensors(prefix_bytes: bytes, nals: list[NALUnit], prefix_end_nal: int) -> tuple[Tensor, Tensor, Tensor]:
    region_chunks: list[Tensor] = []
    offset_chunks: list[Tensor] = []
    for nal in nals[:prefix_end_nal]:
        length = nal.end - nal.start
        region = REGION_META if nal.nal_type in PARAMETER_SET_NAL_TYPES else REGION_TARGET
        region_chunks.append(torch.full((length,), region, dtype=torch.long))
        offset_chunks.append(torch.arange(length, dtype=torch.long))
    raw_region = torch.cat(region_chunks)
    raw_offset = torch.cat(offset_chunks)
    bos = torch.tensor([SLICE_BOS_ID], dtype=torch.long)
    prompt_ids = torch.cat((bos, bytes_to_ids(prefix_bytes)))
    region_ids = torch.cat((torch.tensor([REGION_TARGET], dtype=torch.long), raw_region))
    offset_ids = torch.cat((torch.tensor([0], dtype=torch.long), raw_offset))
    return prompt_ids, region_ids, offset_ids


def _concat_nals(data: bytes, nals: list[NALUnit], start: int, end: int) -> bytes:
    return b"".join(data[nals[i].start : nals[i].end] for i in range(start, end))


def decode_h264(stream: bytes, args: argparse.Namespace, *, strict: bool) -> tuple[list[Tensor], str]:
    command = [args.ffmpeg_binary, "-hide_banner", "-loglevel", "error"]
    if strict:
        command.extend(["-ec", "0", "-err_detect", "explode+bitstream+buffer+compliant"])
    command.extend(
        ["-f", "h264", "-i", "pipe:0", "-vsync", "0", "-f", "image2pipe", "-vcodec", "ppm", "pipe:1"]
    )
    try:
        result = subprocess.run(command, input=stream, capture_output=True, timeout=args.timeout_sec)
    except FileNotFoundError:
        return [], "ffmpeg_not_found"
    except subprocess.TimeoutExpired:
        return [], "timeout"
    if strict and result.returncode != 0:
        return [], "decoder_error"
    if not result.stdout:
        return [], "no_frame"
    frames = parse_ppm_sequence(result.stdout)
    return frames, "decoded" if frames else "no_frame"


def parse_ppm_sequence(data: bytes) -> list[Tensor]:
    frames: list[Tensor] = []
    cursor = 0
    n = len(data)
    while cursor < n:
        if data[cursor : cursor + 2] != b"P6":
            break
        # header: P6 <w> <h> <maxval> then one whitespace byte, then w*h*3 bytes
        fields: list[int] = []
        idx = cursor + 2
        while len(fields) < 3 and idx < n:
            while idx < n and data[idx] in b" \t\n\r":
                idx += 1
            start = idx
            while idx < n and data[idx] not in b" \t\n\r":
                idx += 1
            fields.append(int(data[start:idx]))
        width, height, _ = fields
        idx += 1  # single whitespace after maxval
        payload = idx + width * height * 3
        frames.append(parse_ppm(data[cursor:payload]))
        cursor = payload
    return frames


def save_continuation_videos(
    viz: dict[int, dict[str, Any]], frame_dir: Path, checkpoint_name: str, args: argparse.Namespace,
    tag: str = "continuation",
) -> None:
    if not viz:
        return
    print(f"Saving {len(viz)} {tag} videos for {checkpoint_name}", flush=True)
    for clip_idx, item in viz.items():
        gt = item["gt_frames"]
        model = item["model_frames"]
        if not gt:
            continue
        reference = gt[0]
        missing = torch.zeros_like(reference)
        missing[..., 0] = 1.0
        separator = torch.ones((reference.shape[0], 4, reference.shape[2]), dtype=reference.dtype)
        panels: list[Tensor] = []
        for t in range(len(gt)):
            gt_f = gt[t]
            model_f = model[t] if t < len(model) and model[t].shape == gt_f.shape else missing
            panels.append(torch.cat((gt_f, separator, model_f), dim=1).clamp(0, 1))
        h, w = panels[0].shape[0], panels[0].shape[1]
        pad_h, pad_w = h % 2, w % 2
        if pad_h or pad_w:
            panels = [
                torch.nn.functional.pad(p.permute(2, 0, 1), (0, pad_w, 0, pad_h)).permute(1, 2, 0).contiguous()
                for p in panels
            ]
        height, width = panels[0].shape[0], panels[0].shape[1]
        buffer = b"".join(
            p.mul(255).round().clamp(0, 255).to(torch.uint8).contiguous().numpy().tobytes() for p in panels
        )
        out_path = frame_dir / f"clip_{clip_idx:04d}_{tag}.mp4"
        command = [
            args.ffmpeg_binary, "-y", "-hide_banner", "-loglevel", "error",
            "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{width}x{height}", "-r", str(args.viz_fps),
            "-i", "pipe:0", "-an", "-c:v", "mpeg4", "-q:v", "3", "-pix_fmt", "yuv420p", str(out_path),
        ]
        try:
            subprocess.run(command, input=buffer, capture_output=True, check=True, timeout=args.timeout_sec)
        except (subprocess.CalledProcessError, subprocess.TimeoutExpired, FileNotFoundError) as exc:
            print(f"  continuation video failed for clip {clip_idx}: {exc}", flush=True)
            continue
        # Still of the first generated frame for a quick thumbnail.
        save_png(panels[item["prefix_frames"]] if item["prefix_frames"] < len(panels) else panels[-1],
                 frame_dir / f"clip_{clip_idx:04d}_{tag}_firstgen.png")
        (frame_dir / f"clip_{clip_idx:04d}_{tag}.json").write_text(
            json.dumps(
                {
                    "checkpoint": checkpoint_name,
                    "clip_index": clip_idx,
                    "columns": ["GT", "model"],
                    "prefix_frames": item["prefix_frames"],
                    "generation_starts_at_frame": item["prefix_frames"],
                    "fps": args.viz_fps,
                    "red_tile": "model frame failed to decode",
                    "h264_path": item["h264_path"],
                },
                indent=2,
            )
            + "\n",
            encoding="utf-8",
        )


def append_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    with path.open("a", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(jsonable(row)) + "\n")


def write_summary_csv(path: Path, summaries: list[dict[str, Any]]) -> None:
    if not summaries:
        return
    fieldnames = list(summaries[0].keys())
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        for summary in summaries:
            writer.writerow(summary)


def mean(values: list[float]) -> float | None:
    return float(sum(values) / len(values)) if values else None


if __name__ == "__main__":
    main()
